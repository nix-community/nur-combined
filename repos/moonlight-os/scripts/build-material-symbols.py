#!/usr/bin/env python3
"""Build the trimmed Material Symbols Rounded font used by the Helios web UI.

The upstream variable font carries every symbol Google publishes (~5 MB, ~4400
glyphs), which is far more than a locally served config UI should ship. This
script keeps only the symbols listed in ICONS and emits two artefacts:

  styles/fonts/material-symbols-rounded-subset.woff2  the trimmed font
  icons.js                                            name -> codepoint map

Icons are referenced by codepoint rather than by ligature on purpose: every
symbol name is spelled with the same 27 characters, so keeping the ligature
tables would drag the entire icon set back in. The <Icon> component does the
name lookup instead, so markup still reads as `<Icon name="home" />`.

Requires fonttools (`pip install "fonttools[woff]"`) and the material-symbols
npm package (`npm install --no-save material-symbols`). After using a new icon
in the UI, add it to ICONS below and re-run:

    python3 scripts/build-material-symbols.py
"""

import pathlib
import subprocess
import sys

from fontTools.ttLib import TTFont

ICONS = """
add add_circle admin_panel_settings android apps arrow_back arrow_forward arrow_upward
autorenew block bolt bug_report cancel cast check check_circle chevron_right
close cloud_download code computer contrast content_copy content_paste dark_mode
delete deployed_code_update description desktop_windows devices display_settings dns done download
drag_indicator edit error expand_less expand_more filter_alt folder folder_open
forum fullscreen gavel graphic_eq help high_quality history hub image_search info key
keyboard
lan light_mode link_off list_alt lock lock_open memory menu menu_book mic
monitor monitoring more_vert mouse movie network_node open_in_new
palette password play_arrow power_settings_new qr_code_2 refresh
release_alert remove restart_alt rocket_launch router save science search security settings share shield
sort sort_by_alpha speed sports_esports star stop storage stylus sunny swap_vert
sync tab_group terminal timer touch_app translate troubleshoot tune undo upload usb verified
videocam visibility volume_up vpn_key warning widgets wifi
"""

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "node_modules/material-symbols/material-symbols-rounded.woff2"
WEB = ROOT / "src_assets/common/assets/web"
FONT_OUT = WEB / "styles/fonts/material-symbols-rounded-subset.woff2"
MAP_OUT = WEB / "icons.js"


def main() -> int:
    if not SRC.exists():
        sys.exit(f"missing {SRC}\nrun: npm install --no-save material-symbols")

    names = sorted(set(ICONS.split()))
    cmap = TTFont(SRC).getBestCmap()
    codepoints = {}
    for codepoint, glyph in cmap.items():
        codepoints.setdefault(glyph, codepoint)

    missing = [n for n in names if n not in codepoints]
    if missing:
        sys.exit("unknown symbol names: " + ", ".join(missing))

    FONT_OUT.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "pyftsubset",
            str(SRC),
            f"--output-file={FONT_OUT}",
            "--flavor=woff2",
            "--unicodes=" + ",".join(f"U+{codepoints[n]:04X}" for n in names),
            "--layout-features=",  # ligature tables would pull the full set back in
            "--no-hinting",
            "--desubroutinize",
        ],
        check=True,
    )

    entries = "\n".join(f"  {n}: '\\u{codepoints[n]:04x}'," for n in names)
    MAP_OUT.write_text(
        "// Generated by scripts/build-material-symbols.py -- do not edit by hand.\n"
        "// Material Symbols Rounded codepoints for the symbols bundled in\n"
        "// styles/fonts/material-symbols-rounded-subset.woff2.\n"
        f"export default {{\n{entries}\n}}\n"
    )

    size = FONT_OUT.stat().st_size
    print(f"{len(names)} symbols -> {FONT_OUT.name} ({size / 1024:.0f} KB)")
    print(f"{len(names)} symbols -> {MAP_OUT.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
