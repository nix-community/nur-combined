# shellcheck shell=bash
export LANG=en_US.UTF-8

# Optional package names force-regenerate only those lockfiles.
parse_forced "$@"

# True when a committed lockfile is already current: the source is unchanged and the
# remaining arguments, run as the placeholder test, confirm it holds real content.
# A package with no nvfetcher source cannot be compared, so it is regenerated.
lockfile_current() {
  local attr=$1
  shift
  if [[ "$(source_entry "$attr")" == "null" ]]; then
    echo "Note: $attr has no source in _sources/generated.json; cannot detect changes, regenerating anyway" >&2
    return 1
  fi
  if source_changed "$attr"; then
    return 1
  fi
  "$@"
}

# A pub lock that resolved nothing is a placeholder.
pub_lock_resolved() {
  [[ "$(jq '.packages | length' "$1")" -gt 0 ]]
}

# Regenerate committed Cargo.nix files for changed crate2nix sources using the flake's pinned nixpkgs.
sources_expr="
  let
    flake = builtins.getFlake (toString ./.);
    pkgs = flake.inputs.nixpkgs.legacyPackages.${SYSTEM};
  in
    pkgs.callPackage (flake.outPath + \"/_sources/generated.nix\") {}"

for file in pkgs/*/default.nix; do
  grep --quiet --fixed-strings './Cargo.nix' "$file" || continue
  name=$(basename "$(dirname "$file")")

  if forcing; then
    is_forced "$name" || continue
  else
    if [[ "$(source_entry "$name")" == "null" ]]; then
      echo "Skipping $name: no source named $name in _sources/generated.json" >&2
      continue
    fi
    # Always replace Cargo.nix placeholders lacking the generated header.
    if ! source_changed "$name" && [[ -f "pkgs/$name/Cargo.nix" ]] && grep --quiet '@generated by crate2nix' "pkgs/$name/Cargo.nix"; then
      continue
    fi
  fi

  echo "Regenerating pkgs/$name/Cargo.nix"
  mark_handled "$name"
  src=$(nix build --no-link --print-out-paths --impure --expr "($sources_expr).\"$name\".src")

  tmp=$(mktemp -d)
  cp -r "$src/." "$tmp/src"
  chmod -R u+w "$tmp/src"

  # Use the root manifest or the sole first-level manifest with a deterministic relative path.
  manifest_args=()
  if [[ ! -f "$tmp/src/Cargo.toml" ]]; then
    shopt -s nullglob
    manifests=("$tmp/src"/*/Cargo.toml)
    shopt -u nullglob
    if [[ ${#manifests[@]} -ne 1 ]]; then
      echo "ERROR: $name: no root Cargo.toml and ${#manifests[@]} first-level manifests; cannot pick one" >&2
      exit 1
    fi
    manifest_args=(-f "$(basename "$(dirname "${manifests[0]}")")/Cargo.toml")
  fi

  # Reconcile stale upstream Cargo.lock files before crate2nix runs metadata with `--locked`.
  heal_args=()
  if [[ ${#manifest_args[@]} -gt 0 ]]; then
    heal_args=(--manifest-path "${manifest_args[1]}")
  fi
  (cd "$tmp/src" && cargo metadata --format-version 1 "${heal_args[@]}" >/dev/null)

  (cd "$tmp/src" && crate2nix generate "${manifest_args[@]}")

  cp "$tmp/src/Cargo.nix" "pkgs/$name/Cargo.nix"
  rm -rf "$tmp"
done

# Regenerate changed gomod2nix locks and their dependency cache package list.
while IFS= read -r toml; do
  attr="$(basename "$(dirname "$toml")")"
  if forcing; then
    is_forced "$attr" || continue
  fi
  if nix eval ".#packages.${SYSTEM}.$attr.pname" >/dev/null 2>&1; then
    # A lock lacking real module entries is a placeholder.
    if ! is_forced "$attr" && lockfile_current "$attr" grep --quiet '^\s*\[mod\.' "$toml"; then
      continue
    fi
    echo "Regenerating gomod2nix.toml for $attr"
    mark_handled "$attr"
    src="$(nix build --no-link --print-out-paths ".#packages.${SYSTEM}.${attr}.src")"
    gomod2nix generate --with-deps --dir "$src" --outdir "pkgs/$attr"
  else
    echo "Skipping $toml: no matching flake package" >&2
  fi
done < <(find pkgs -name gomod2nix.toml)

# Regenerate committed pub locks for changed Flutter sources. Upstream projects
# often gitignore pubspec.lock, so resolution happens here and lands as JSON.
while IFS= read -r lockfile; do
  attr="$(basename "$(dirname "$lockfile")")"
  if forcing; then
    is_forced "$attr" || continue
  fi
  # Flutter packages are Linux-only here, so darwin runs skip them.
  if nix eval ".#packages.${SYSTEM}.$attr.pname" >/dev/null 2>&1; then
    if ! is_forced "$attr" && lockfile_current "$attr" pub_lock_resolved "$lockfile"; then
      continue
    fi
    echo "Regenerating $lockfile"
    mark_handled "$attr"

    # The package names the SDK it resolves against; the runner stays generic.
    sdk="$(nix build --no-link --print-out-paths ".#packages.${SYSTEM}.${attr}.pubLockFlutter")"
    src=$(nix build --no-link --print-out-paths --impure --expr "($sources_expr).\"$attr\".src")

    tmp=$(mktemp -d)
    cp -r "$src/." "$tmp/src"
    chmod -R u+w "$tmp/src"

    # Pub resolution needs a writable HOME and network access.
    (
      export HOME="$tmp/home"
      export PUB_CACHE="${PUB_CACHE:-$tmp/pub-cache}"
      mkdir -p "$HOME"
      cd "$tmp/src" || exit
      "$sdk/bin/flutter" --no-version-check config --no-analytics >/dev/null
      "$sdk/bin/flutter" --no-version-check pub get >&2
    )

    yq eval --output-format=json --prettyPrint "$tmp/src/pubspec.lock" >"$lockfile"

    # A Flutter SDK is several gigabytes and is only needed when upstream
    # releases, but gc-store roots every package's build closure — so an SDK
    # left behind here would ride the shared store cache from now on. Nix
    # keeps whatever is still live, so a partial sweep is expected and fine.
    echo "Dropping the $attr SDK from the store"
    nix-store --query --requisites "$sdk" >"$tmp/sdk-paths"
    xargs -a "$tmp/sdk-paths" -r sudo "$(command -v nix-store)" --delete || true

    rm -rf "$tmp"
  else
    echo "Skipping $lockfile: no matching flake package" >&2
  fi
done < <(find pkgs -name pubspec.lock.json)

warn_unhandled "regenerated (not a crate2nix/gomod2nix/pub package or no matching flake package)"
