def load_existing(build_dir: Path) -> dict[str, dict]:
    p = build_dir / GENERATED_JSON
    if not p.exists():
        return {}
    try:
        return json.loads(p.read_text())
    except json.JSONDecodeError:
        return {}


def main():
    ap = argparse.ArgumentParser(
        prog="update-sources", description="Python nvfetcher alternative"
    )
    ap.add_argument("-c", "--config", default="nvfetcher.toml")
    ap.add_argument("-o", "--build-dir", default="_sources")
    ap.add_argument("-f", "--filter", help="Regex; only matching packages are updated")
    ap.add_argument("-k", "--keyfile", help="nvchecker keyfile")
    ap.add_argument(
        "-j", "--jobs", type=int, default=8, help="parallel prefetch workers"
    )
    ap.add_argument(
        "-t", "--tries", type=int, default=3, help="nvchecker network retries"
    )
    ap.add_argument(
        "--force", action="store_true", help="re-fetch even if version unchanged"
    )
    args = ap.parse_args()

    config_path = Path(args.config)
    build_dir = Path(args.build_dir)
    packages = load_config(config_path)
    existing = load_existing(build_dir)

    if args.filter:
        rx = re.compile(args.filter)
        active = {n: p for n, p in packages.items() if rx.search(n)}
    else:
        active = dict(packages)

    # Pinned packages and filtered-out packages keep their existing entry.
    to_check: dict[str, Package] = {}
    results: dict[str, dict] = {}
    skipped: list[str] = []

    for name, pkg in packages.items():
        if name not in active or pkg.pinned:
            old = existing.get(name)
            if old is not None:
                results[name] = old
                skipped.append(name)
            continue
        to_check[name] = pkg

    # 1. nvchecker
    versions: dict[str, str] = {}
    errors: dict[str, str] = {}
    if to_check:
        versions, errors = run_nvchecker(
            build_nvchecker_config(to_check, args.keyfile), args.tries
        )
        for name, err in errors.items():
            if name not in versions:
                sys.stderr.write(f"[nvchecker] {name}: {err}\n")

    # 2. decide what to fetch
    fetch_tasks: dict[str, tuple[Package, str]] = {}
    for name, pkg in to_check.items():
        new_ver = versions.get(name)
        if new_ver is None:
            old = existing.get(name)
            if old is not None:
                results[name] = old
                sys.stderr.write(f"[keep] {name}: nvchecker failed, keeping existing\n")
            else:
                sys.stderr.write(
                    f"[drop] {name}: nvchecker failed and no existing entry\n"
                )
            continue
        old = existing.get(name)
        if (
            old is not None
            and old.get("version") == new_ver
            and not args.force
            and not pkg.force_fetch
        ):
            results[name] = old
            continue
        fetch_tasks[name] = (pkg, new_ver)

    # 3. prefetch in parallel
    def do_fetch(item):
        name, (pkg, ver) = item
        src = prefetch_package(pkg, ver)
        date = None
        if src is not None and pkg.is_git_source:
            try:
                date = get_git_date(
                    str(pkg.src["git"]), ver, pkg.date_format, pkg.date_tz
                )
                if not date:
                    date = None
            except Exception as e:  # noqa: BLE001
                sys.stderr.write(f"[date] {name}: {e}\n")
                date = (existing.get(name) or {}).get("date")
        return name, ver, src, date

    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        for name, ver, src, date in ex.map(do_fetch, fetch_tasks.items()):
            if src is None:
                old = existing.get(name)
                if old is not None:
                    results[name] = old
                    sys.stderr.write(
                        f"[keep] {name}: prefetch failed, keeping existing\n"
                    )
                else:
                    sys.stderr.write(
                        f"[drop] {name}: prefetch failed and no existing entry\n"
                    )
                continue
            res = {"version": ver, "src": src, "pinned": packages[name].pinned}
            if date:
                res["date"] = date
            elif packages[name].is_git_source and existing.get(name, {}).get("date"):
                res["date"] = existing[name]["date"]
            if packages[name].passthru:
                res["passthru"] = packages[name].passthru
            if packages[name].extract:
                res["extract"] = packages[name].extract
            results[name] = res

    # 4. write outputs
    build_dir.mkdir(parents=True, exist_ok=True)
    write_nix(build_dir / GENERATED_NIX, results)
    write_json(build_dir / GENERATED_JSON, results)

    changed = sum(
        1
        for n in results
        if n not in skipped
        and existing.get(n, {}).get("version") != results[n].get("version")
    )
    sys.stderr.write(
        f"done: {len(results)} packages kept/written, {changed} version changes, "
        f"{len(skipped)} kept as-is (pinned/filtered/unchanged)\n"
    )


if __name__ == "__main__":
    main()
