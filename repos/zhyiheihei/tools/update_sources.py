def _prefetch_git(url, rev, opts, name=None):
    cmd = ["nix-prefetch-git", "--url", url, "--rev", rev]
    if opts["fetchSubmodules"]:
        cmd.append("--fetch-submodules")
    if opts["deepClone"]:
        cmd.append("--deepClone")
    if opts["leaveDotGit"]:
        cmd.append("--leave-dotGit")
    if opts["sparseCheckout"]:
        cmd += ["--sparse-checkout", "\n".join(opts["sparseCheckout"])]
    r = run(cmd, stdout=subprocess.PIPE)
    data = json.loads(r.stdout)
    return to_sri(data["sha256"]), data.get("date", "")


def _prefetch_url(url, unpack=False, name=None):
    cmd = ["nix-prefetch-url", url]
    if unpack:
        cmd.append("--unpack")
    if name:
        cmd += ["--name", name]
    r = run(cmd, stdout=subprocess.PIPE)
    return to_sri(last_line(r.stdout))


def _prefetch_docker(image, tag, docker_opts):
    cmd = ["nix-prefetch-docker", "--json", image, tag]
    for opt in ("os", "arch"):
        if docker_opts.get(opt):
            cmd += [f"--{opt}", docker_opts[opt]]
    r = run(cmd, stdout=subprocess.PIPE)
    data = json.loads(r.stdout)
    digest = data.get("imageDigest") or data.get("digest")
    sha = data.get("sha256") or data.get("hash")
    return to_sri(sha), digest


def get_git_date(url, rev, date_format=None, date_tz=None):
    fmt = date_format or "%Y-%m-%d"
    env = dict(os.environ)
    if date_tz and date_tz != "local":
        env["TZ"] = date_tz
    with tempfile.TemporaryDirectory() as repo:
        run(
            ["git", "init"],
            cwd=repo,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        run(
            ["git", "remote", "add", "origin", url],
            cwd=repo,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        run(
            ["git", "fetch", "--depth", "1", "origin", rev],
            cwd=repo,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        run(
            ["git", "checkout", "FETCH_HEAD"],
            cwd=repo,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        flag = "--date=format-local" if date_tz else "--date=format"
        r = run(
            ["git", "--no-pager", "log", "-1", "--format=%cd", f"{flag}:{fmt}"],
            cwd=repo,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
        )
        return r.stdout.strip()


def prefetch_package(pkg: Package, version: str) -> dict | None:
    """Run the appropriate nix fetcher and return the generated.json ``src`` dict."""
    fk = pkg.fetcher
    opts = pkg.git_opts()
    try:
        if fk == "github":
            owner, repo = str(pkg.fetch["github"]).split("/", 1)
            rev = version
            need_git = (
                opts["fetchSubmodules"]
                or opts["deepClone"]
                or opts["leaveDotGit"]
                or bool(opts["sparseCheckout"])
            )
            if need_git:
                sha, _ = _prefetch_git(f"https://github.com/{owner}/{repo}", rev, opts)
            else:
                sha = _prefetch_url(
                    f"https://github.com/{owner}/{repo}/archive/{rev}.tar.gz",
                    unpack=True,
                )
            return {
                "type": "github",
                "owner": owner,
                "repo": repo,
                "rev": rev,
                "deepClone": opts["deepClone"],
                "fetchSubmodules": opts["fetchSubmodules"],
                "leaveDotGit": opts["leaveDotGit"],
                "sparseCheckout": opts["sparseCheckout"],
                "name": None,
                "sha256": sha,
            }
        if fk == "git":
            url = str(pkg.fetch["git"])
            rev = version
            sha, _ = _prefetch_git(url, rev, opts)
            return {
                "type": "git",
                "url": url,
                "rev": rev,
                "deepClone": opts["deepClone"],
                "fetchSubmodules": opts["fetchSubmodules"],
                "leaveDotGit": opts["leaveDotGit"],
                "sparseCheckout": opts["sparseCheckout"],
                "name": None,
                "sha256": sha,
            }
        if fk == "pypi":
            pypi = str(pkg.fetch["pypi"])
            url = f"https://pypi.org/packages/source/{pypi[0]}/{pypi}/{pypi}-{version}.tar.gz"
            sha = _prefetch_url(url)
            return {"type": "url", "url": url, "name": None, "sha256": sha}
        if fk == "url":
            url = str(pkg.fetch["url"]).replace("$ver", version)
            name = pkg.url.get("name")
            if name is not None:
                name = str(name).replace("$ver", version)
            sha = _prefetch_url(url, name=name)
            return {"type": "url", "url": url, "name": name, "sha256": sha}
        if fk == "tarball":
            url = str(pkg.fetch["tarball"]).replace("$ver", version)
            sha = _prefetch_url(url, unpack=True)
            return {"type": "tarball", "url": url, "sha256": sha}
        if fk == "openvsx":
            publisher, ext = str(pkg.fetch["openvsx"]).split(".", 1)
            url = f"https://open-vsx.org/api/{publisher}/{ext}/{version}/file/{publisher}.{ext}-{version}.vsix"
            name = f"{ext}-{version}.zip"
            sha = _prefetch_url(url, name=name)
            return {"type": "url", "url": url, "name": name, "sha256": sha}
        if fk == "vsmarketplace":
            publisher, ext = str(pkg.fetch["vsmarketplace"]).split(".", 1)
            url = (
                f"https://{publisher}.gallery.vsassets.io/_apis/public/gallery/"
                f"publisher/{publisher}/extension/{ext}/{version}/"
                f"assetbyname/Microsoft.VisualStudio.Services.VSIXPackage"
            )
            name = f"{ext}-{version}.zip"
            sha = _prefetch_url(url, name=name)
            return {"type": "url", "url": url, "name": name, "sha256": sha}
        if fk == "docker":
            image = str(pkg.fetch["docker"])
            sha, digest = _prefetch_docker(image, version, pkg.docker)
            return {
                "type": "docker",
                "imageName": image,
                "imageTag": version,
                "imageDigest": digest,
                "sha256": sha,
                "os": pkg.docker.get("os"),
                "arch": pkg.docker.get("arch"),
                "finalImageName": pkg.docker.get("finalImageName"),
                "finalImageTag": pkg.docker.get("finalImageTag") or version,
                "tlsVerify": pkg.docker.get("tlsVerify"),
            }
    except subprocess.CalledProcessError as e:
        sys.stderr.write(f"[fetch] {pkg.name}: {e}\n")
        if e.stderr:
            sys.stderr.write(e.stderr + "\n")
        return None
    except Exception as e:  # noqa: BLE001
        sys.stderr.write(f"[fetch] {pkg.name}: {e}\n")
        return None
    return None


