def run_nvchecker(
    config_text: str, tries: int
) -> tuple[dict[str, str], dict[str, str]]:
    with tempfile.NamedTemporaryFile("w", suffix=".toml", delete=False) as f:
        f.write(config_text)
        cfg = f.name
    try:
        r = subprocess.run(
            ["nvchecker", "--logger", "json", "-t", str(tries), "-c", cfg],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
    finally:
        os.unlink(cfg)

    versions: dict[str, str] = {}
    errors: dict[str, str] = {}
    for line in r.stdout.splitlines():
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            continue
        ev = obj.get("event")
        name = obj.get("name")
        if not name:
            continue
        if ev == "updated" and obj.get("version") is not None:
            versions[name] = obj["version"]
        elif ev in ("no-result", "error"):
            errors[name] = obj.get("error", ev)
    return versions, errors


