#!/usr/bin/env nix-shell
#!nix-shell -i python3 -p python3 -p nvchecker -p nix -p nix-prefetch-scripts -p nix-prefetch-docker -p git
"""Python reimplementation of nvfetcher.

Behavior differences from upstream nvfetcher:
  * Version checking delegates to the same ``nvchecker`` tool, and every
    nvchecker source type is accepted (nvfetcher's mapped subset plus a
    generic passthrough for the rest, or an explicit ``src.source``).
  * Reads ``nvfetcher.toml`` and writes ``_sources/generated.{nix,json}`` in
    the same format.  The output already reflects what this repo's
    ``postprocess_nvfetcher.py`` used to do (``hash``/``tag`` and default
    fields stripped), so that script no longer needs to run afterwards.
  * On any per-package failure (nvchecker error or prefetch error) the existing
    entry from ``generated.json`` is kept instead of aborting or dropping it.
"""

