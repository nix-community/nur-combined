# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------


def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    kw.setdefault("text", True)
    kw.setdefault("check", True)
    kw.setdefault("stderr", subprocess.PIPE)
    return subprocess.run(cmd, **kw)


def nix_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${") + '"'


def nix_ident(name: str) -> str:
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_'-]*", name):
        return name
    return nix_quote(name)


def to_sri(sha256: str) -> str:
    if sha256.startswith("sha256-"):
        return sha256
    out = run(
        ["nix", "hash", "to-sri", "--type", "sha256", sha256.strip()],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
    )
    return out.stdout.strip()


def last_line(stdout: str) -> str:
    for line in reversed(stdout.splitlines()):
        if line.strip():
            return line.strip()
    return ""


def is_commit_hash(rev: str) -> bool:
    return bool(re.fullmatch(r"[0-9a-f]{40}", rev))


