# output serialization (final, post-processed format)
# ---------------------------------------------------------------------------


def _nix_bool(b) -> str:
    return "true" if b else "false"


def _nix_list(items) -> str:
    if not items:
        return "[ ]"
    return "[ " + " ".join(nix_quote(i) for i in items) + " ]"


def src_to_nix(src: dict) -> str:
    t = src.get("type")
    if t == "github":
        owner, repo, rev = src["owner"], src["repo"], src["rev"]
        fs = src.get("fetchSubmodules", False)
        dc = src.get("deepClone", False)
        ldg = src.get("leaveDotGit", False)
        sc = src.get("sparseCheckout", []) or []
        name = src.get("name")
        rev_field = "rev" if is_commit_hash(rev) else "tag"
        lines = [
            "    src = fetchFromGitHub {",
            f"      owner = {nix_quote(owner)};",
            f"      repo = {nix_quote(repo)};",
            f"      {rev_field} = {nix_quote(rev)};",
        ]
        if fs:
            lines.append(f"      fetchSubmodules = {_nix_bool(fs)};")
        if dc:
            lines.append(f"      deepClone = {_nix_bool(dc)};")
        if ldg:
            lines.append(f"      leaveDotGit = {_nix_bool(ldg)};")
        if sc:
            lines.append(f"      sparseCheckout = {_nix_list(sc)};")
        if name is not None:
            lines.append(f"      name = {nix_quote(name)};")
        lines.append(f"      hash = {nix_quote(src['sha256'])};")
        lines.append("    }")
        return "\n".join(lines)
    if t == "git":
        lines = [
            "    src = fetchgit {",
            f"      url = {nix_quote(src['url'])};",
            f"      rev = {nix_quote(src['rev'])};",
        ]
        # fetchgit always carries fetchSubmodules (matches the committed
        # output of this repo's old postprocess step).
        lines.append(
            f"      fetchSubmodules = {_nix_bool(src.get('fetchSubmodules', False))};"
        )
        if src.get("deepClone"):
            lines.append(f"      deepClone = {_nix_bool(src['deepClone'])};")
        if src.get("leaveDotGit"):
            lines.append(f"      leaveDotGit = {_nix_bool(src['leaveDotGit'])};")
        if src.get("sparseCheckout"):
            lines.append(f"      sparseCheckout = {_nix_list(src['sparseCheckout'])};")
        if src.get("name") is not None:
            lines.append(f"      name = {nix_quote(src['name'])};")
        lines.append(f"      hash = {nix_quote(src['sha256'])};")
        lines.append("    }")
        return "\n".join(lines)
    if t == "url":
        lines = ["    src = fetchurl {", f"      url = {nix_quote(src['url'])};"]
        if src.get("name") is not None:
            lines.append(f"      name = {nix_quote(src['name'])};")
        lines.append(f"      hash = {nix_quote(src['sha256'])};")
        lines.append("    }")
        return "\n".join(lines)
    if t == "tarball":
        lines = [
            "    src = fetchTarball {",
            f"      url = {nix_quote(src['url'])};",
            f"      hash = {nix_quote(src['sha256'])};",
            "    }",
        ]
        return "\n".join(lines)
    if t == "docker":
        lines = [
            "    src = dockerTools.pullImage {",
            f"      imageName = {nix_quote(src['imageName'])};",
            f"      imageDigest = {nix_quote(src['imageDigest'])};",
            f"      hash = {nix_quote(src['sha256'])};",
            f"      finalImageTag = {nix_quote(src.get('finalImageTag') or src['imageTag'])};",
        ]
        for k, v in (
            ("os", "os"),
            ("arch", "arch"),
            ("finalImageName", "finalImageName"),
        ):
            if src.get(v) is not None:
                lines.append(f"      {k} = {nix_quote(src[v])};")
        if src.get("tlsVerify") is not None:
            lines.append(f"      tlsVerify = {_nix_bool(src['tlsVerify'])};")
        lines.append("    }")
        return "\n".join(lines)
    raise ValueError(f"unknown src type: {t}")


def result_to_nix(name: str, res: dict) -> str:
    lines = [
        f"  {nix_ident(name)} = {{",
        f"    pname = {nix_quote(name)};",
        f"    version = {nix_quote(res['version'])};",
        src_to_nix(res["src"]) + ";",
    ]
    extract = res.get("extract")
    if extract:
        lines.append("    extract = {")
        for src_path, dst_path in extract.items():
            lines.append(
                f"      {nix_ident(src_path)} = ./. + {nix_quote('/' + dst_path)};"
            )
        lines.append("    };")
    cargo = res.get("cargoLock")
    if cargo:
        for lock_src, info in cargo.items():
            lines.append(f"    cargoLock.{nix_quote(lock_src)} = {{")
            lines.append(f"      lockFile = ./. + {nix_quote('/' + info['lockFile'])};")
            lines.append("      outputHashes = {")
            for dep, h in info.get("outputHashes", {}).items():
                lines.append(f"        {nix_quote(dep)} = {nix_quote(h)};")
            lines.append("      };")
            lines.append("    };")
    passthru = res.get("passthru")
    if passthru:
        for k, v in passthru.items():
            lines.append(f"    {nix_ident(k)} = {nix_quote(str(v))};")
    if res.get("date"):
        lines.append(f"    date = {nix_quote(res['date'])};")
    lines.append("  };")
    return "\n".join(lines)


def write_nix(path: Path, results: dict[str, dict]):
    body = "\n".join(result_to_nix(n, results[n]) for n in sorted(results))
    path.write_text(NIX_HEADER + body + "\n}\n")


def write_json(path: Path, results: dict[str, dict]):
    obj = {}
    for name in sorted(results):
        res = results[name]
        obj[name] = {
            "cargoLock": res.get("cargoLock"),
            "date": res.get("date"),
            "extract": res.get("extract"),
            "name": name,
            "passthru": res.get("passthru"),
            "pinned": bool(res.get("pinned", False)),
            "src": res["src"],
            "version": res["version"],
        }
    path.write_text(json.dumps(obj, indent=4, sort_keys=True) + "\n")


