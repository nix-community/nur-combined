# Source modules shipped by nvchecker, discovered at runtime from the
# installed ``nvchecker_source`` package so newly added nvchecker sources are
# recognized without code changes.  We deliberately do not keep a fallback:
# if nvchecker's structure changes significantly, discovery fails loudly.


def _discover_nvchecker_sources() -> set[str]:
    import importlib
    import pkgutil

    mod = importlib.import_module("nvchecker_source")
    return {m.name for m in pkgutil.iter_modules(mod.__path__)}


NVCK_SOURCES = _discover_nvchecker_sources()

# ``src`` keys that are options rather than a source identifier.
AUX_KEYS = {
    "branch",
    "regex",
    "include_regex",
    "exclude_regex",
    "sort_version_key",
    "ignored",
    "prefix",
    "from_pattern",
    "to_pattern",
    "prerelease",
    "source",
}

FETCHERS = [
    "github",
    "git",
    "pypi",
    "url",
    "tarball",
    "docker",
    "openvsx",
    "vsmarketplace",
]


class Package:
    def __init__(self, name, raw):
        self.name = name
        self.src = raw.get("src", {}) or {}
        self.fetch = raw.get("fetch", {}) or {}
        self.git = raw.get("git", {}) or {}
        self.url = raw.get("url", {}) or {}
        self.docker = raw.get("docker", {}) or {}
        self.passthru = raw.get("passthru") or None
        self.extract = raw.get("extract") or None
        self.cargo_lock = raw.get("cargo_lock") or None
        self.pinned = bool(raw.get("pinned", False))
        self.date_format = self.git.get("date_format")
        self.date_tz = self.git.get("date_tz")
        self.force_fetch = bool(raw.get("fetch", {}).get("force", False))

    @property
    def vsource(self):
        for k in VERSION_SOURCES:
            if k in self.src:
                return k
        return None

    @property
    def fetcher(self):
        for k in FETCHERS:
            if k in self.fetch:
                return k
        return None

    @property
    def is_git_source(self):
        return self.vsource == "git"

    def git_opts(self):
        return {
            "deepClone": bool(self.git.get("deepClone", False)),
            "fetchSubmodules": bool(self.git.get("fetchSubmodules", False)),
            "leaveDotGit": bool(self.git.get("leaveDotGit", False)),
            "sparseCheckout": list(self.git.get("sparseCheckout", []) or []),
        }


def load_config(path: Path) -> dict[str, Package]:
    with open(path, "rb") as f:
        raw = tomllib.load(f)
    pkgs = {}
    for name, body in raw.items():
        if not isinstance(body, dict):
            continue
        pkgs[name] = Package(name, body)
    return pkgs


