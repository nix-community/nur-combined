def _toml_key(k: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9_-]+", k):
        return k
    return json.dumps(k)


def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int) and not isinstance(v, bool):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return (
            "{"
            + ", ".join(f"{_toml_key(k)} = {_toml_value(x)}" for k, x in v.items())
            + "}"
        )
    return json.dumps(str(v))


def _detect_source_key(src: dict) -> str | None:
    if "source" in src:
        return "source"
    for k in VERSION_SOURCES:
        if k in src:
            return k
    for k in src:
        if k in NVCK_SOURCES and k not in AUX_KEYS:
            return k
    return None


# For each mapped source, the set of ``src`` keys the mapping consumes (so they
# are not emitted again verbatim).
_CONSUMED = {
    "github": {"github", "prerelease"},
    "github_tag": {"github_tag"},
    "git": {"git", "branch"},
    "pypi": {"pypi"},
    "aur": {"aur"},
    "archpkg": {"archpkg"},
    "manual": {"manual"},
    "repology": {"repology"},
    "webpage": {"webpage", "regex"},
    "httpheader": {"httpheader", "regex"},
    "openvsx": {"openvsx"},
    "vsmarketplace": {"vsmarketplace"},
    "cmd": {"cmd"},
    "container": {"container"},
}


def _mapped_entries(src: dict, vs: str) -> list[tuple[str, object]]:
    """Return the nvchecker (key, value) pairs produced by the nvfetcher mapping."""
    if vs == "github":
        out = [
            ("source", "github"),
            ("github", src["github"]),
            ("use_latest_release", "true"),
        ]
        if src.get("prerelease"):
            out.append(("include_prereleases", "true"))
        return out
    if vs == "github_tag":
        return [
            ("source", "github"),
            ("github", src["github_tag"]),
            ("use_max_tag", "true"),
        ]
    if vs == "git":
        out = [("source", "git"), ("git", src["git"]), ("use_commit", "true")]
        if src.get("branch"):
            out.append(("branch", src["branch"]))
        return out
    if vs == "pypi":
        return [("source", "pypi"), ("pypi", src["pypi"])]
    if vs == "aur":
        return [("source", "aur"), ("aur", src["aur"]), ("strip_release", "true")]
    if vs == "archpkg":
        return [
            ("source", "archpkg"),
            ("archpkg", src["archpkg"]),
            ("strip_release", "true"),
        ]
    if vs == "manual":
        return [("source", "manual"), ("manual", src["manual"])]
    if vs == "repology":
        project, repo = str(src["repology"]).split(":", 1)
        return [("source", "repology"), ("repology", project), ("repo", repo)]
    if vs == "webpage":
        return [("source", "regex"), ("url", src["webpage"]), ("regex", src["regex"])]
    if vs == "httpheader":
        return [
            ("source", "httpheader"),
            ("url", src["httpheader"]),
            ("regex", src["regex"]),
        ]
    if vs == "openvsx":
        return [("source", "openvsx"), ("openvsx", src["openvsx"])]
    if vs == "vsmarketplace":
        return [("source", "vsmarketplace"), ("vsmarketplace", src["vsmarketplace"])]
    if vs == "cmd":
        return [("source", "cmd"), ("cmd", src["cmd"])]
    if vs == "container":
        return [("source", "container"), ("container", src["container"])]
    return []


def build_nvchecker_config(packages: dict[str, Package], keyfile: str | None) -> str:
    lines = []
    if keyfile:
        lines.append("[__config__]")
        lines.append(f"keyfile = {json.dumps(keyfile)}")
        lines.append("")
    for name, pkg in packages.items():
        lines.append(f"[{json.dumps(name)}]")
        src = pkg.src
        skey = _detect_source_key(src)
        if skey is None:
            lines.append('source = "none"')
            lines.append("")
            continue
        consumed: set[str] = set()
        if skey == "source":
            # Explicit passthrough: emit everything from src verbatim.
            lines.append(f"source = {_toml_value(src['source'])}")
            consumed.add("source")
        elif skey in _CONSUMED:
            for k, v in _mapped_entries(src, skey):
                lines.append(f"{_toml_key(k)} = {_toml_value(v)}")
            consumed = _CONSUMED[skey]
        else:
            # Generic nvchecker source, e.g. src.cratesio / src.gitlab / src.npm.
            lines.append(f"source = {_toml_value(skey)}")
            lines.append(f"{_toml_key(skey)} = {_toml_value(src[skey])}")
            consumed.add(skey)
        # Emit any remaining src keys (list/tweak options and extra nvchecker
        # options) verbatim.
        for k, v in src.items():
            if k in consumed:
                continue
            lines.append(f"{_toml_key(k)} = {_toml_value(v)}")
        lines.append("")
    return "\n".join(lines)


