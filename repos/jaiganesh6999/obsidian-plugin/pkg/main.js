// src/main.ts
var SEOWebCheckerPlugin = class extends import_obsidian3.Plugin {
  async onload() {
    await this.loadSettings();
    this.analyzer = new MarkdownSEOAnalyzer(this.settings);
    this.registerView(
      VIEW_TYPE_SEO_AUDIT,
      (leaf) => new SEOWebCheckerView(leaf, this)
    );
    this.addRibbonIcon("gauge", "SEOWebChecker SEO Audit", () => {
      void this.activateView();
    });
    this.addCommand({
      id: "open-seo-audit-view",
      name: "Open SEO Audit Sidebar",
      callback: () => {
        void this.activateView();
      }
    });
    this.addCommand({
      id: "audit-current-note",
      name: "Audit Current Note",
      checkCallback: (checking) => {
        const view = this.app.workspace.getActiveViewOfType(import_obsidian3.MarkdownView);
        if (view) {
          if (!checking) {
            this.triggerAudit();
            new import_obsidian3.Notice("SEOWebChecker: Audit updated for active note.");
          }
          return true;
        }
        return false;
      }
    });
    this.addCommand({
      id: "insert-seo-frontmatter-template",
      name: "Insert SEO Frontmatter Template",
      editorCallback: (editor, view) => {
        const title = view.file ? view.file.basename : "Article Title";
        const template = `---
title: "${title}"
description: "Write a compelling 120-165 character summary describing the core value of this article."
canonical: "https://example.com/blog/article-slug"
focus_keyword: "primary target term"
slug: "${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}"
---

`;
        const curDoc = editor.getValue();
        if (curDoc.startsWith("---")) {
          new import_obsidian3.Notice("Note already contains YAML frontmatter.");
        } else {
          editor.replaceRange(template, { line: 0, ch: 0 });
          new import_obsidian3.Notice("Inserted SEO frontmatter template.");
          this.triggerAudit();
        }
      }
    });
    this.addSettingTab(new SEOWebCheckerSettingTab(this.app, this));
    const debouncedAudit = (0, import_obsidian3.debounce)(
      () => {
        if (this.settings.enableRealtimeAudit) {
          this.triggerAudit();
        }
      },
      600,
      true
    );
    this.registerEvent(
      this.app.workspace.on("editor-change", () => {
        debouncedAudit();
      })
    );
    this.registerEvent(
      this.app.workspace.on("active-leaf-change", () => {
        this.triggerAudit();
      })
    );
  }
  onunload() {
  }
  async loadSettings() {
    const loaded = await this.loadData();
    this.settings = Object.assign({}, DEFAULT_SETTINGS, loaded != null ? loaded : {});
  }
  async saveSettings() {
    await this.saveData(this.settings);
    this.analyzer = new MarkdownSEOAnalyzer(this.settings);
    this.triggerAudit();
  }
  async activateView() {
    const { workspace } = this.app;
    let leaf = null;
    const leaves = workspace.getLeavesOfType(VIEW_TYPE_SEO_AUDIT);
    if (leaves.length > 0) {
      leaf = leaves[0];
    } else {
      leaf = workspace.getRightLeaf(false);
      if (leaf) {
        await leaf.setViewState({
          type: VIEW_TYPE_SEO_AUDIT,
          active: true
        });
      }
    }
    if (leaf) {
      await workspace.revealLeaf(leaf);
      this.triggerAudit();
    }
  }
  triggerAudit() {
    const activeView = this.app.workspace.getActiveViewOfType(import_obsidian3.MarkdownView);
    if (!activeView || !activeView.file) {
      return;
    }
    const content = activeView.editor.getValue();
    const noteTitle = activeView.file.basename;
    const result = this.analyzer.analyze(content, noteTitle);
    const leaves = this.app.workspace.getLeavesOfType(VIEW_TYPE_SEO_AUDIT);
    leaves.forEach((leaf) => {
      if (leaf.view instanceof SEOWebCheckerView) {
        leaf.view.updateAudit(result);
      }
    });
  }
};
