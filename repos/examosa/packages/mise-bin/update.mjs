#!/usr/bin/env -S nix
/*
#! nix shell nixpkgs#nodejs nixpkgs#nix --command node
*/

import { execFileSync } from "node:child_process";
import { rename, writeFile } from "node:fs/promises";
import { STATUS_CODES } from "node:http";
import { tmpdir } from "node:os";
import { join } from "node:path";

const platforms = {
  "aarch64-darwin": "macos-arm64",
  "aarch64-linux": "linux-arm64-musl",
  "x86_64-linux": "linux-x64-musl",
};

const run = (command, args) =>
  execFileSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();

async function getLatestVersion() {
  const response = await fetch(
    "https://api.github.com/repos/jdx/mise/releases/latest",
    { headers: { Accept: "application/vnd.github+json" } },
  );

  if (!response.ok) {
    throw new Error(
      `HTTP ${response.status}: ${response.statusText || STATUS_CODES[response.status]}`,
    );
  }

  const release = await response.json();

  return release.tag_name;
}

const args = process.argv.slice(2);

if (args.length > 1) {
  throw new RangeError(`Usage: ${process.argv[1]} [version]`);
}

const version = (args[0] ?? (await getLatestVersion())).replace(/^v/, "");

if (!/^\d+\.\d+\.\d+$/.test(version)) {
  throw new RangeError(`Invalid release version: ${version}`);
}

function prefetch(asset, { unpack = false } = {}) {
  const url = `https://github.com/jdx/mise/releases/download/v${version}/${asset}`;

  const result = run("nix", [
    "store",
    "prefetch-file",
    "--json",
    "--hash-type",
    "sha256",
    ...(unpack ? ["--unpack"] : []),
    url,
  ]);

  return JSON.parse(result).hash;
}

const archiveExtension = "tar.xz";

const archives = Object.entries(platforms).map(([system, suffix]) => {
  const asset = `mise-v${version}-${suffix}.${archiveExtension}`;
  return [system, { asset, hash: prefetch(asset, { unpack: true }) }];
});

const completions = ["bash", "fish", "zsh"].map((shell) => {
  const asset = `mise.${shell}`;
  return [shell, { asset, hash: prefetch(asset) }];
});

const renderAssets = (entries) =>
  entries
    .map(([name, { asset, hash }]) => {
      const isArchive = asset.endsWith(archiveExtension);

      return `    ${name} = fetchAsset {
      asset = "${asset}";
      ${isArchive ? `extension = "${archiveExtension}"` : "extract = false"};
      hash = "${hash}";
    };`;
    })
    .join("\n\n");

const sources = `# Generated by ./update.mjs; do not edit manually.

{fetchGitHubReleaseAsset}: let
  version = "${version}";

  fetchAsset = args:
    fetchGitHubReleaseAsset (args
      // {
        owner = "jdx";
        repo = "mise";
        tag = "v\${version}";
      });
in {
  inherit version;

  archives = {
${renderAssets(archives)}
  };

  completions = {
${renderAssets(completions)}
  };
}
`;

const output = new URL("sources.nix", import.meta.url);

const tmp = join(
  tmpdir(),
  "sources.nix." + Math.random().toString(36).slice(2),
);

await writeFile(tmp, sources, { mode: 0o644 });
await rename(tmp, output);
