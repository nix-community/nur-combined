#!/usr/bin/env nix
/*
#! nix shell nixpkgs#nodejs nixpkgs#nix nixpkgs#nix-prefetch --command node
*/

import { execFileSync } from "node:child_process";
import { rename, writeFile } from "node:fs/promises";
import { STATUS_CODES } from "node:http";

const platforms = {
  mise: {
    "aarch64-darwin": "macos-arm64",
    "aarch64-linux": "linux-arm64-musl",
    "x86_64-linux": "linux-x64-musl",
  },
  rust: {
    "aarch64-darwin": "aarch64-apple-darwin",
    "aarch64-linux": "aarch64-unknown-linux-musl",
    "x86_64-linux": "x86_64-unknown-linux-musl",
  },
};

const packages = {
  mise: {
    owner: "jdx",
    platforms: platforms.mise,
    archive: (suffix, version) => `mise-v${version}-${suffix}.tar.xz`,
  },
  aube: {
    owner: "aubepkg",
    platforms: platforms.rust,
    archive: (suffix, version) => `aube-v${version}-${suffix}.tar.gz`,
  },
  fnox: {
    owner: "jdx",
    platforms: platforms.rust,
    archive: (suffix) => `fnox-${suffix}.tar.gz`,
  },
};

const run = (command, args) =>
  execFileSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();

async function getLatestVersion(owner, repo) {
  const response = await fetch(
    `https://api.github.com/repos/${owner}/${repo}/releases/latest`,
    { headers: { Accept: "application/vnd.github+json" } },
  );

  if (!response.ok) {
    throw new Error(
      `HTTP ${response.status}: ${response.statusText || STATUS_CODES[response.status]}`,
    );
  }

  const release = await response.json();

  return release.tag_name;
}

const [repo, requestedVersion, ...rest] = process.argv.slice(2);
const config = Object.hasOwn(packages, repo) && packages[repo];

if (!config || rest.length > 0) {
  throw new RangeError(`Usage: ${process.argv[1]} <mise|aube|fnox> [version]`);
}

const version = (
  requestedVersion ?? (await getLatestVersion(config.owner, repo))
).replace(/^v/, "");

if (!/^\d+\.\d+\.\d+$/.test(version)) {
  throw new RangeError(`Invalid release version: ${version}`);
}

const archivePattern = /(?<=\.)tar\.[gx]z$/;
const stripRoot = repo === "mise";

function prefetch(asset) {
  const url = `https://github.com/${config.owner}/${repo}/releases/download/v${version}/${asset}`;
  const extension = asset.match(archivePattern)?.[0];

  const [fetcher, options] = extension
    ? [
        "fetchzip",
        ["--extension", extension, "--stripRoot", "--expr", String(stripRoot)],
      ]
    : ["fetchurl", []];

  const result = run("nix-prefetch", [
    "--option",
    "show-trace",
    "true",
    fetcher,
    "--url",
    url,
    ...options,
  ]);

  const hash = run("nix", [
    "hash",
    "convert",
    "--hash-algo",
    "sha256",
    "--to",
    "sri",
    result,
  ]);

  return { asset, hash };
}

const archives = Object.entries(config.platforms).map(([system, suffix]) => {
  const asset = config.archive(suffix, version);
  return [system, prefetch(asset)];
});

const usage = prefetch(`${repo}.usage.kdl`);

function renderAsset(name, { asset, hash }, level = 1) {
  const extension = asset.match(archivePattern)?.[0];

  const lines = [
    `${name} = fetchAsset {`,
    `asset = "${asset}"`,
    extension ? `extension = "${extension}"` : "extract = false",
    `hash = "${hash}"`,
    "}",
  ];

  if (extension && !stripRoot) {
    lines.splice(4, 0, "stripRoot = false");
  }

  return lines
    .map((line, index) => {
      const leading = index === 0;
      const offset = Number(!leading && index < lines.length - 1);
      const indent = " ".repeat((offset + level) * 2);
      return indent + line + (leading ? "" : ";");
    })
    .join("\n");
}

const renderAssets = (entries) =>
  entries.map((args) => renderAsset(...args, 2)).join("\n\n");

const sources = `# Generated by ../scripts/update.mjs ${repo}; do not edit manually.

{fetchGitHubReleaseAsset}: let
  version = "${version}";

  fetchAsset = args:
    fetchGitHubReleaseAsset (args
      // {
        owner = "${config.owner}";
        repo = "${repo}";
        tag = "v\${version}";
      });
in {
  inherit version;

  archives = {
${renderAssets(archives)}
  };

${renderAsset("usage", usage)}
}
`;

const output = new URL(`../packages/${repo}-bin/sources.nix`, import.meta.url);

const tmp = new URL(
  `sources.nix.${process.pid}.${Math.random().toString(36).slice(2)}.tmp`,
  output,
);

await writeFile(tmp, sources, { mode: 0o644 });
await rename(tmp, output);
