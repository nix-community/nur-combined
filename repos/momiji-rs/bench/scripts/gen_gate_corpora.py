def build() -> dict[str, str]:
    """Every file this generator owns, as `{path relative to OUT_DIR: text}`."""
    files = {
        "legacy_deprecations.scss": legacy_deprecations(),
        "extend_heavy.scss": extend_heavy(),
        "selector_lists.scss": selector_lists(),
        "module_calls.scss": module_calls(),
        "user_functions.scss": user_functions(),
    }
    for rel, text in use_graph().items():
        files["use_graph/" + rel] = text
    for rel, text in star_forward().items():
        files["star_forward/" + rel] = text
    for rel, text in extend_modules().items():
        files["extend_modules/" + rel] = text
    return files


def manifest(files: dict[str, str]) -> str:
    entries = {
        rel: {
            "bytes": len(text.encode()),
            "sha256": hashlib.sha256(text.encode()).hexdigest()[:16],
        }
        for rel, text in sorted(files.items())
    }
    return (
        json.dumps(
            {
                "generatorVersion": GENERATOR_VERSION,
                "generator": "bench/scripts/gen_gate_corpora.py",
                "expectedMarker": MARKER,
                "files": entries,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify, write nothing")
    args = ap.parse_args()

    files = build()
    files["MANIFEST.json"] = manifest(files)

    if args.check:
        drift = []
        for rel, want in sorted(files.items()):
            path = OUT_DIR / rel
            got = path.read_text() if path.exists() else None
            if got != want:
                drift.append(rel if got is not None else rel + " (missing)")
        for rel in drift:
            print("DRIFT %s" % rel, file=sys.stderr)
        print(
            "%d files checked, %d differ" % (len(files), len(drift)),
            file=sys.stderr,
        )
        return 1 if drift else 0

    for rel, text in sorted(files.items()):
        path = OUT_DIR / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    total = sum(len(t.encode()) for t in files.values())
    print(
        "wrote %d files, %d bytes to %s"
        % (len(files), total, OUT_DIR.relative_to(REPO_ROOT)),
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
