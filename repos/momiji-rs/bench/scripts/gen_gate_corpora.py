# 6 sections x 5 components + 2 token files + 3 vendor files + 2 entries = 43
# files in the corpus, of which either entry loads 42 -- close to the 36-file
# real-world shape the modular corpus mirrors.
USE_SECTIONS = 6
USE_COMPONENTS_PER_SECTION = 5


SELECTOR_LIST_GROUPS = 120
SELECTOR_LIST_WIDTH = 4


def selector_lists() -> str:
    """Multi-line comma selector lists, and a few selectors dart-sass drops.

    This corpus exists because of a gap, not because of a lever. `share_current`
    in `eval_style_rule` is the fast path that skips the per-complex rebuild,
    and it is false whenever the rule carries per-complex line-break flags --
    which is to say whenever the author wrote a comma selector list across
    lines, the normal shape of hand-written CSS. Every other corpus here, and
    `large.scss`, has exactly ZERO of those, so the slow branch was never
    benchmarked: work added to it was not merely unmeasured but unmeasurable.

    Three properties, each for a reason:

    * **The lists span lines.** A single-line `a, b {` does not set the flags;
      the newline is what does.
    * **The lists are nested.** `current_linebreaks` is handed to every
      descendant rule, so a nested body inherits the branch from its parent --
      the poisoning chain, and the reason one list at the top of a file is
      enough to move a whole sheet onto it.
    * **A few of them are bogus.** A repeated combinator run (`> +`) is dropped
      from the output with a `bogus-combinators` warning, which is the only
      shape that reaches the span-mapping added for #119/#120. Kept rare, the
      way it is in real sheets, so the corpus measures the common branch and
      merely visits the rare one.
    """
    out = [HEADER]

    for g in range(1, SELECTOR_LIST_GROUPS + 1):
        names = ",\n".join(
            "  .grp-%d-%d .item" % (g, k) for k in range(1, SELECTOR_LIST_WIDTH + 1)
        )
        out.append(
            """%s {
  color: #%02x%02x%02x;
  margin-block: %dpx;

  .nested-a,
  .nested-b {
    padding-inline: %dpx;
    &:hover { opacity: 0.%d; }
  }
}
"""
            % (
                names.lstrip(),
                (g * 7) % 256,
                (g * 13) % 256,
                (g * 29) % 256,
                g % 12,
                g % 9,
                g % 9 + 1,
            )
        )

    # The dropped shape, at roughly the density a real sheet carries it.
    for g in range(1, SELECTOR_LIST_GROUPS // 20 + 1):
        out.append(
            """.bogus-%d >  + .tail,
.bogus-%d >  + .tail .inner {
  border-width: %dpx;
}
"""
            % (g, g, g % 4 + 1)
        )

    # `corpora_still_compile` asserts on this: a corpus that silently stopped
    # compiling would otherwise be timed as a fast failure.
    out.append("%s { --generated: true; }\n" % MARKER)
    return "".join(out)


def use_graph() -> dict[str, str]:
    """A multi-file `@use` graph, and the same graph reached twice over.

    Returns a `{relative path: contents}` map rooted at `gate/use_graph/`.

    `entry.scss` loads each section once; `redundant.scss` loads the sections
    *and* every component and token file directly, so ~40 modules are reached
    through two paths instead of one. Both must produce identical CSS: `@use`
    is idempotent, and that is precisely why probing the module cache before
    calling the importer is safe -- and why a corpus that only ever loads a
    module once cannot show it.

    The vendored `lib` package resolves through a load path
    (`gate/use_graph/vendor`), not relatively, so the benchmark also exercises
    the load-path arm of `FsImporter::canonicalize` -- the arm that records
    dependencies for `--quiet-deps`.
    """
    files: dict[str, str] = {}

    files["_tokens.scss"] = HEADER + """$space: 4px;
$radius: 3px;
$brand: #3498db;
$accent: #e67e22;
$muted: #7f8c8d;
$sizes: (sm: 4px, md: 8px, lg: 16px, xl: 32px);
$weights: (light: 300, normal: 400, bold: 700);
"""

    files["_mixins.scss"] = HEADER + """@use "sass:color";
@use "tokens" as t;

@mixin surface($tint) {
  background: color.mix($tint, white, 12%);
  border: 1px solid color.mix($tint, black, 88%);
  border-radius: t.$radius;
}

@mixin stack($gap: t.$space) {
  display: flex;
  flex-direction: column;
  gap: $gap;
}

// Emitted once by the entry so a benchmark can assert the graph compiled.
@mixin gate-marker {
  """ + MARKER + """ { --generated: true; }
}
"""

    for s in range(1, USE_SECTIONS + 1):
        for c in range(1, USE_COMPONENTS_PER_SECTION + 1):
            tint = ["t.$brand", "t.$accent", "t.$muted"][(s + c) % 3]
            files["components/_c%d_%d.scss" % (s, c)] = HEADER + """@use "sass:color";
@use "sass:math";
@use "../tokens" as t;
@use "../mixins" as m;

.c%d-%d {
  @include m.surface(%s);
  @include m.stack(t.$space * %d);
  color: color.adjust(%s, $lightness: -%d%%);

  @each $name, $size in t.$sizes {
    &--#{$name} {
      padding: $size math.div($size, 2);
      font-size: math.div($size, 2) + 8px;
    }
  }

  .icon {
    width: t.$space * %d;
    &:hover { color: color.adjust(%s, $saturation: %d%%); }
  }
}
""" % (s, c, tint, c % 4 + 1, tint, c * 3, c + 2, tint, c * 5)

    for s in range(1, USE_SECTIONS + 1):
        body = ['@use "../tokens" as t;', '@use "../mixins" as m;']
        for c in range(1, USE_COMPONENTS_PER_SECTION + 1):
            body.append('@use "../components/c%d_%d";' % (s, c))
        body.append("")
        body.append(".section-%d { @include m.stack(t.$space * 2); }" % s)
        files["sections/_s%d.scss" % s] = HEADER + "\n".join(body) + "\n"

    files["vendor/lib/_index.scss"] = HEADER + """@forward "reset";
@forward "grid";
"""
    files["vendor/lib/_reset.scss"] = HEADER + """*, *::before, *::after { box-sizing: border-box; }
body { margin: 0; font-family: system-ui, sans-serif; }
"""
    files["vendor/lib/_grid.scss"] = HEADER + """@use "sass:math";

$columns: 12;

@for $i from 1 through $columns {
  .col-#{$i} { width: math.percentage(math.div($i, $columns)); }
}
"""

    entry = [
        HEADER.rstrip("\n"),
        '@use "lib"; // vendored: resolves through the `vendor` load path',
        '@use "mixins" as m;',
    ]
    for s in range(1, USE_SECTIONS + 1):
        entry.append('@use "sections/s%d";' % s)
    entry += ["", "@include m.gate-marker;", ""]
    files["entry.scss"] = "\n".join(entry)

    # The same graph, every module also loaded directly by the entry. `@use` is
    # idempotent, so this compiles to the same CSS as `entry.scss` while asking
    # the importer about ~40 modules that are already in the module cache.
    redundant = [
        HEADER.rstrip("\n"),
        "// The redundant-`@use` case: identical output to `entry.scss`, reached",
        "// through roughly twice as many load requests.",
        '@use "lib";',
        '@use "tokens";',
        '@use "mixins" as m;',
    ]
    for s in range(1, USE_SECTIONS + 1):
        redundant.append('@use "sections/s%d";' % s)
    for s in range(1, USE_SECTIONS + 1):
        for c in range(1, USE_COMPONENTS_PER_SECTION + 1):
            redundant.append('@use "components/c%d_%d";' % (s, c))
    redundant += ["", "@include m.gate-marker;", ""]
    files["redundant.scss"] = "\n".join(redundant)

    return files


