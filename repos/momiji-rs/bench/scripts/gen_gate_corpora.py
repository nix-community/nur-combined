# ----------------------------------------------------------------- corpus 1

# 150 x 8 = 1200 mixin includes over 13 deprecated call sites. The call sites
# live INSIDE the mixin on purpose: every include reports the same ~13 spans,
# which is what makes this a saturated test of the deprecation dedup and memo
# rather than a test of how fast 15600 distinct warnings can be constructed.
DEPRECATION_REPEATS = 150
PALETTE = [
    "#3498db",
    "#e74c3c",
    "#2ecc71",
    "#f1c40f",
    "#9b59b6",
    "#1abc9c",
    "#e67e22",
    "#34495e",
]


def legacy_deprecations() -> str:
    """A legacy-deprecation-dense sheet: the A1 lever's best case.

    Every function named here is deprecated in dart-sass 1.103 -- either a
    global built-in with a module equivalent, or one of the legacy colour
    functions -- so each `@include` walks the whole diagnostics path: the
    `deprecates()` name check, the dedup key, and (for the colour functions)
    the replacement suggestion.
    """
    out = [HEADER]
    out.append("$palette: (%s);\n" % ", ".join(PALETTE))
    out.append(
        """@mixin legacy($c) {
  color: darken($c, 20%);
  border-color: lighten($c, 10%);
  background: saturate($c, 15%);
  outline-color: desaturate($c, 5%);
  box-shadow: 0 0 2px transparentize($c, 0.3);
  fill: opacify($c, 0.2);
  stroke: adjust-hue($c, 30deg);
  --r: #{red($c)};
  --g: #{green($c)};
  --h: #{hue($c)};
  --s: #{saturation($c)};
  --l: #{lightness($c)};
}
"""
    )
    out.append(
        """@for $i from 1 through %d {
  @each $c in $palette {
    .legacy-#{$i}-#{index($palette, $c)} { @include legacy($c); }
  }
}
"""
        % DEPRECATION_REPEATS
    )
    out.append("%s { --generated: true; }\n" % MARKER)
    return "".join(out)


# ----------------------------------------------------------------- corpus 2

# `@extend` cost grows super-linearly (measured exponent ~1.8 before the A2
# lever, ~1.4-1.6 after), so these counts are chosen for a compile in the same
# order of magnitude as `large.scss` rather than for the largest possible delta.
# 6 roots x 4 bases x 3 concretes, plus 4 combo placeholders, 6 class variants
# and 4 media blocks, measured 7.6 ms/compile and showed the A2 prototype at
# -49.7% (macOS/arm64, 2026-09-16).
EXTEND_ROOTS = 6
EXTEND_BASES_PER_ROOT = 4
EXTEND_CONCRETES_PER_BASE = 3
EXTEND_MEDIA_QUERIES = 4
EXTEND_NESTED_EVERY = 3


def extend_heavy() -> str:
    """An `@extend`-heavy sheet: the A2 lever's corpus.

    Three properties matter, and all three come from real frameworks rather
    than from what is convenient to generate:

    * **Chains.** A placeholder extends a placeholder, and a concrete selector
      extends that, so `extend_to_fixpoint` actually iterates instead of
      settling in one pass.
    * **Class extends, not only placeholders.** Extending a `.class` leaves the
      extended rule in the output and multiplies its selector list, which is
      the case the extend store indexes.
    * **Nested and at-rule contexts.** `@extend` inside a nested rule and
      inside `@media` is where the extender's own selector has to be resolved
      against its parent before it can be registered.
    """
    out = [HEADER]

    for r in range(1, EXTEND_ROOTS + 1):
        out.append(
            """%%root-%d {
  box-sizing: border-box;
  display: inline-flex;
  font: inherit 1rem/%s sans-serif;
  transition: color %dms ease-in-out;
}
"""
            % (r, "1.%d" % (r % 7 + 2), 80 + r * 5)
        )

    for r in range(1, EXTEND_ROOTS + 1):
        for b in range(1, EXTEND_BASES_PER_ROOT + 1):
            out.append(
                """%%base-%d-%d {
  @extend %%root-%d;
  border: %dpx solid rgba(0, 0, 0, 0.%d);
  padding: %dpx %dpx;
  &:focus-visible { outline: 2px solid #3498db; }
}
"""
                % (r, b, r, b % 3 + 1, (r + b) % 9 + 1, b * 2, b * 3)
            )

    # A second layer of placeholders, each extending two bases from different
    # roots: the transitive closure is what the fixpoint loop is for.
    for b in range(1, EXTEND_BASES_PER_ROOT + 1):
        left = (b - 1) % EXTEND_ROOTS + 1
        right = b % EXTEND_ROOTS + 1
        out.append(
            """%%combo-%d {
  @extend %%base-%d-%d;
  @extend %%base-%d-%d;
  gap: %dpx;
}
"""
            % (b, left, b, right, b, b + 1)
        )

    n = 0
    for r in range(1, EXTEND_ROOTS + 1):
        for b in range(1, EXTEND_BASES_PER_ROOT + 1):
            for c in range(1, EXTEND_CONCRETES_PER_BASE + 1):
                n += 1
                # Only every EXTEND_NESTED_EVERY'th concrete extends from a
                # nested context. Every one of them doing so is a fine
                # microbenchmark and a poor CI corpus: the first shape tried
                # here (12 roots x 8 bases x 4 concretes, all of them nested)
                # measured 442 ms/compile against this one's 7.6 ms, buying a
                # bigger delta with ~58x the runner time.
                nested = (
                    "\n  .inside & { @extend %%combo-%d; }"
                    % ((b + c - 1) % EXTEND_BASES_PER_ROOT + 1)
                    if n % EXTEND_NESTED_EVERY == 0
                    else ""
                )
                out.append(
                    """.c-%d-%d-%d {
  @extend %%base-%d-%d;
  color: #%02x%02x%02x;%s
}
"""
                    % (r, b, c, r, b, r * 17 % 256, b * 29 % 256, c * 53 % 256, nested)
                )

    # Extending a class rather than a placeholder: `.btn` survives into the
    # output and grows a selector list, which placeholders never do.
    out.append(
        """.btn {
  appearance: none;
  cursor: pointer;
}
"""
    )
    for r in range(1, EXTEND_ROOTS + 1):
        out.append(
            """.btn-variant-%d {
  @extend .btn;
  background: hsl(%d, 60%%, 50%%);
}
"""
            % (r, r * 29 % 360)
        )

    # `@extend` inside `@media` -- with the extended selector inside the same
    # query, because dart-sass rejects extending across one ("You may not
    # @extend selectors across media queries"), which is itself a reason this
    # corpus has to be compiled rather than assumed correct.
    for q in range(1, EXTEND_MEDIA_QUERIES + 1):
        out.append(
            """@media (min-width: %dpx) {
  %%mq-%d {
    display: grid;
    grid-template-columns: repeat(%d, minmax(0, 1fr));
  }
  .responsive-%d { @extend %%mq-%d; }
  .responsive-%d .nested { @extend %%mq-%d; }
  .responsive-%d:not(.plain) { @extend %%mq-%d; }
}
"""
            % (320 * q, q, q + 1, q, q, q, q, q, q)
        )

    out.append("%s { --generated: true; }\n" % MARKER)
    return "".join(out)


