#!/usr/bin/env python3
"""Generator for the corpora the CI performance gate was missing.

`benches/compile.rs` protects only the shapes that happen to be in
`bench/corpus/generated/`, and three planned improvements measure *zero* there
(`docs/PERF_PLAN_2026-09-16.md`, B4). This script emits the shapes where they
are visible, so that landing them and later regressing them are distinguishable
in CI:

  gate/legacy_deprecations.scss  legacy colour functions called from one mixin,
                                 so ~13 spans repeat ~1200 times: the
                                 deprecation bookkeeping path, and the most
                                 sensitive early warning for the whole
                                 diagnostics area.
  gate/extend_heavy.scss         placeholder and class `@extend` in chains and
                                 inside nested/at-rule contexts, the shape that
                                 real frameworks hit and `large.scss` does not
                                 contain at all.
  gate/use_graph/**              a multi-file `@use` graph, plus a second entry
                                 that reaches every module through two paths
                                 (the redundant-`@use` case).
  gate/selector_lists.scss       multi-line comma selector lists, which is the
                                 ONLY way to reach `eval_style_rule`'s
                                 `share_current == false` branch -- the one
                                 every other corpus, `large.scss` included,
                                 leaves at zero.
  gate/module_calls.scss         built-in calls written the module-system way
                                 (`map.get`, `color.adjust`, `list.nth`), the
                                 shape a sheet written with `@use` has. Every
                                 other corpus calls globals, or only
                                 `math.div`, which returns before the general
                                 module path; that path was measured nowhere.
  gate/user_functions.scss       a design-token sheet built from its own
                                 `@function`s and `@mixin`s, with five
                                 modules `@use`d. No other corpus defines a
                                 single `@function`, so the user-callable path
                                 (argument binding, the environment swap, the
                                 call frame) was measured nowhere.
  gate/star_forward/**           large modules reached through `@forward` and
                                 several `@use ... as *`, the shape of a design
                                 system such as uswds: a variable is looked up
                                 in each starred module before the one that has
                                 it, and every miss used to scan the module.
  gate/extend_modules/**         `@extend` across a graph of modules: placeholders
                                 in one shared module, extended from many
                                 component modules. Single-file `extend_heavy`
                                 cannot reach the per-module-scope store-merge
                                 ordering this exercises.

Deterministic by construction -- no PRNG, no clock, no environment -- so
re-running rewrites byte-identical files. The output is checked into git, like
`bench/corpus/generated/large.scss`, because `benches/compile.rs` reads it with
`include_str!` and the benchmark must not depend on a generator having been run.

Usage:
    python3 bench/scripts/gen_gate_corpora.py           # rewrite in place
    python3 bench/scripts/gen_gate_corpora.py --check    # verify, write nothing

`--check` exits non-zero if any file on disk differs from what this script
would emit, which is what makes MANIFEST.json worth having: it says which
generator version produced the corpus, so a hand-edit is visible.
"""

