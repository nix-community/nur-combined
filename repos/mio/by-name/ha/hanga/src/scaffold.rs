//! `hanga init-mod` — write a self-contained starter WASM mod.
//!
//! The generated crate is standalone: it carries its own copy of the sandbox
//! WIT and builds with `wasm32-unknown-unknown` + `wasm-tools component new`.
//! No dependency on the `nurpkgs` tree, so a mod author can iterate with plain
//! `cargo` and load the result with `hanga --mod ./<name>.wasm`.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Crate names cannot contain `-`; mods may. Keep the file/game name, fix the crate.
pub fn crate_name(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        out.push_str("hanga_mod");
    }
    if out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    out
}

fn cargo_toml(crate_name: &str) -> String {
    format!(
        r#"[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2024"

[lib]
# cdylib so `wasm32-unknown-unknown` links a real component.
crate-type = ["cdylib"]

[lints.rust]
unexpected_cfgs = {{ level = "warn", check-cfg = ['cfg(kani)'] }}

[dependencies]
wit-bindgen = "0.60.0"
"#
    )
}

fn lib_rs(name: &str) -> String {
    format!(
        r#"//! {name} — a Hanga WASM component mod (generated by `hanga init-mod`).
//!
//! Build:
//!   cargo build --release --target wasm32-unknown-unknown
//!   wasm-tools component new target/wasm32-unknown-unknown/release/{crate}.wasm -o {name}.wasm
//!
//! Play:
//!   hanga --mod ./{name}.wasm
//!
//! The host sandbox ABI lives in `wit/world.wit`. `invoke` is the one named
//! entry point (`Object.call` / Luanti `othermod.api()`): return `empty` (or an
//! empty string) for "not mine", and `fail` only for a real bus error
//! (`busy` / `self` / `noproc`).

wit_bindgen::generate!({{ world: "plugin", path: "wit" }});

use hanga::engine::host::{{Cell, Value}};

/// One JSON node. The wire is a cell arena because WIT types cannot recurse.
fn text(value: &str) -> Value {{
    Value {{
        cells: vec![Cell::Text(value.to_string())],
        root: 0,
    }}
}}

fn empty() -> Value {{
    Value {{
        cells: vec![Cell::Empty],
        root: 0,
    }}
}}

struct Mod;

impl exports::hanga::engine::guest::Guest for Mod {{
    /// ABI major the host loads. Current host wants 6.
    fn abi() -> i32 {{
        6
    }}

    /// Godot `_ready`: once after every pack in the collection exists.
    fn ready() {{}}

    /// Voxel names in meshing-index order. Index 0 must be air.
    fn voxel_catalog() -> Vec<String> {{
        ["air", "stone"].iter().map(|name| name.to_string()).collect()
    }}

    /// Worldgen hot path. Return the catalog index. Air is 0.
    fn query_voxel(_x: i32, y: i32, _z: i32) -> i32 {{
        if y < 0 {{ 1 }} else {{ 0 }}
    }}

    /// Named methods. Answer the ones you own; `empty` means "not mine".
    fn invoke(_caller: String, method: String, _args: Value) -> Value {{
        match method.as_str() {{
            "name" => text("{name}"),
            "ping" => text("pong"),
            "catalog" => text("air,stone"),
            _ => empty(),
        }}
    }}
}}

export!(Mod);
"#,
        crate = crate_name(name),
    )
}

