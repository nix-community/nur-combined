fn readme(name: &str) -> String {
    format!(
        r#"# {name}

A Hanga WASM component mod, generated by `hanga init-mod`.

## Build

`lld` / `wasm-ld` and `wasm-tools` must be on `PATH`.

```sh
cargo build --release --target wasm32-unknown-unknown
wasm-tools component new \
  target/wasm32-unknown-unknown/release/{crate}.wasm \
  -o {name}.wasm
```

## Play

```sh
hanga --mod ./{name}.wasm
```

`hanga --mod` makes an implicit one-mod game with a neutral menu. Put a
`{name}.game` next to the WASM and set `HANGA_GAMES` to have the menu cycle it
with its own chrome; the same file also seeds `HANGA_MODS` when it sits beside
the `.wasm`.

## Where to go next

- World rules: `query_voxel` (lead mod owns terrain), `voxel-catalog`.
- Player hooks: answer `invoke` methods the host asks for — `gravity`,
  `player-spawn`, `evaluate-action`, `loot-item`, `craft-result`, `fracture-kit`,
  `vehicle-kit`, `steer`, `fire-kit`, `on-step`, `before-dig`, …
- Mod-to-mod: `host::invoke`, `host::send`, `host::emit`, `host::has_mod`.
- The full sandbox ABI is in `wit/world.wit`.
"#,
        crate = crate_name(name),
    )
}

/// Write a starter mod into `root/<name>`. Returns the directory it created.
///
/// `wit_dir` is copied to `<dir>/wit` so the crate builds without the host tree.
pub fn write_starter_mod(root: &Path, name: &str, wit_dir: &Path) -> io::Result<PathBuf> {
    let dir = root.join(name);
    if dir.exists() {
        return Err(io::Error::new(
            io::ErrorKind::AlreadyExists,
            format!("{} already exists", dir.display()),
        ));
    }
    fs::create_dir_all(dir.join("src"))?;
    fs::create_dir_all(dir.join("wit"))?;

    fs::write(dir.join("Cargo.toml"), cargo_toml(&crate_name(name)))?;
    fs::write(dir.join("src").join("lib.rs"), lib_rs(name))?;
    fs::write(dir.join(format!("{name}.game")), game_file(name))?;
    fs::write(dir.join("README.md"), readme(name))?;

    let mut copied = 0usize;
    if wit_dir.is_dir() {
        for entry in fs::read_dir(wit_dir)? {
            let entry = entry?;
            let path = entry.path();
            if path.extension().is_some_and(|ext| ext == "wit") {
                fs::copy(&path, dir.join("wit").join(entry.file_name()))?;
                copied += 1;
            }
        }
    }
    if copied == 0 {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!(
                "no .wit files in {} (set HANGA_WIT to the host sandbox ABI)",
                wit_dir.display()
            ),
        ));
    }
    Ok(dir)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp_root(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("hanga-scaffold-{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn write_wit(dir: &Path) {
        fs::create_dir_all(dir).unwrap();
        fs::write(dir.join("world.wit"), "package hanga:engine;\n").unwrap();
    }

    #[test]
    fn crate_names_are_valid_rust_identifiers() {
        assert_eq!(crate_name("My Mod"), "my_mod");
        assert_eq!(crate_name("urban-chaos"), "urban_chaos");
        assert_eq!(crate_name("9lives"), "_9lives");
        assert_eq!(crate_name(""), "hanga_mod");
    }

    #[test]
    fn writes_a_buildable_layout() {
        let root = tmp_root("layout");
        let wit = root.join("wit-src");
        write_wit(&wit);
        let dir = write_starter_mod(&root, "hello-world", &wit).unwrap();
        assert!(dir.join("Cargo.toml").is_file());
        assert!(dir.join("src/lib.rs").is_file());
        assert!(dir.join("hello-world.game").is_file());
        assert!(dir.join("README.md").is_file());
        assert!(dir.join("wit/world.wit").is_file());

        let lib = fs::read_to_string(dir.join("src/lib.rs")).unwrap();
        assert!(lib.contains("fn abi() -> i32"));
        assert!(lib.contains("\"hello-world\""));
        let cargo = fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(cargo.contains("name = \"hello_world\""));
        let game = fs::read_to_string(dir.join("hello-world.game")).unwrap();
        assert!(game.contains("id=hello-world"));
        assert!(game.contains("mods=hello-world"));
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn refuses_to_clobber_and_needs_wit() {
        let root = tmp_root("refuse");
        let wit = root.join("wit-src");
        write_wit(&wit);
        write_starter_mod(&root, "dupe", &wit).unwrap();
        assert!(write_starter_mod(&root, "dupe", &wit).is_err());

        let empty = root.join("no-wit");
        fs::create_dir_all(&empty).unwrap();
        assert!(write_starter_mod(&root, "blank", &empty).is_err());
        fs::remove_dir_all(&root).unwrap();
    }
}
