package androidx.media3.common

interface Player {
    var playWhenReady: Boolean
    val playbackState: Int
    var repeatMode: Int
    val currentTimeline: Timeline
    val currentMediaItemIndex: Int
    var shuffleModeEnabled: Boolean
    val mediaItemCount: Int
    val isPlaying: Boolean
    val isLoading: Boolean
    val duration: Long
    val currentPosition: Long
    val bufferedPosition: Long
    val totalBufferedDuration: Long
    val currentMediaItem: MediaItem?

    fun prepare()
    fun play()
    fun pause()
    fun stop()
    fun release()
    fun seekToDefaultPosition()
    fun seekToDefaultPosition(mediaItemIndex: Int)
    fun seekTo(positionMs: Long)
    fun seekTo(mediaItemIndex: Int, positionMs: Long)
    fun seekToPrevious()
    fun seekToNext()
    fun seekToPreviousMediaItem()
    fun seekToNextMediaItem()
    fun setMediaItem(mediaItem: MediaItem)
    fun setMediaItems(mediaItems: List<MediaItem>)
    fun setMediaItems(mediaItems: List<MediaItem>, startIndex: Int, startPositionMs: Long)
    fun addMediaItem(mediaItem: MediaItem)
    fun addMediaItem(index: Int, mediaItem: MediaItem)
    fun addMediaItems(mediaItems: List<MediaItem>)
    fun addMediaItems(index: Int, mediaItems: List<MediaItem>)
    fun removeMediaItem(index: Int)
    fun removeMediaItems(fromIndex: Int, toIndex: Int)
    fun clearMediaItems()
    fun moveMediaItem(currentIndex: Int, newIndex: Int)
    fun moveMediaItems(fromIndex: Int, toIndex: Int, newIndex: Int)
    fun replaceMediaItem(index: Int, mediaItem: MediaItem)
    fun replaceMediaItems(fromIndex: Int, toIndex: Int, mediaItems: List<MediaItem>)
    fun getMediaItemAt(index: Int): MediaItem
    fun hasNextMediaItem(): Boolean
    fun hasPreviousMediaItem(): Boolean
    fun setPlaybackSpeed(speed: Float)
    fun setShuffleOrder(shuffleOrder: Any)
    fun setVideoSurface(surface: Any?)
    fun clearVideoSurface(surface: Any?)
    fun clearVideoSurface()
    fun setVideoSurfaceTexture(surfaceTexture: Any?)
    fun clearVideoSurfaceTexture()
    fun isCommandAvailable(command: Int): Boolean = true
    // `setVolume` is generated by the `var volume` property below; declaring both clashes.
    fun addListener(listener: Listener)
    fun removeListener(listener: Listener)

    val audioSessionId: Int
    val bufferedPercentage: Int
    val availableCommands: Commands
    val videoSize: VideoSize?
    val playerError: PlaybackException?
    val isInitialized: Boolean
    var playbackParameters: PlaybackParameters
    var trackSelectionParameters: TrackSelectionParameters
    val pauseAtEndOfMediaItems: Boolean
    var volume: Float
    val maxSeekToPreviousPosition: Long
    val nextMediaItemIndex: Int
    val previousMediaItemIndex: Int
    val isCurrentMediaItemLive: Boolean
    val isCurrentMediaItemSeekable: Boolean
    val isCurrentMediaItemDynamic: Boolean

    fun togglePlayPause()
    fun toggleRepeatMode()
    fun setPauseAtEndOfMediaItems(pauseAtEndOfMediaItems: Boolean)
    fun hasNext(): Boolean
    fun hasPrevious(): Boolean
    fun setMediaItem(mediaItem: MediaItem, resetPosition: Boolean)
    fun setMediaItems(mediaItems: List<MediaItem>, resetPosition: Boolean)

    interface Listener {
        fun onPlaybackStateChanged(playbackState: Int) {}

        fun onPlayWhenReadyChanged(playWhenReady: Boolean, reason: Int) {}

        fun onPlaybackSuppressionReasonChanged(playbackSuppressionReason: Int) {}

        fun onIsPlayingChanged(isPlaying: Boolean) {}

        fun onMediaItemTransition(mediaItem: MediaItem?, reason: Int) {}

        fun onPositionDiscontinuity(
            oldPosition: PositionInfo,
            newPosition: PositionInfo,
            reason: Int,
        ) {}

        fun onShuffleModeEnabledChanged(shuffleModeEnabled: Boolean) {}

        fun onRepeatModeChanged(repeatMode: Int) {}

        fun onTimelineChanged(timeline: Timeline, reason: Int) {}

        fun onTracksChanged(tracks: Tracks) {}

        fun onMediaMetadataChanged(mediaMetadata: MediaMetadata) {}

        fun onPlaylistMetadataChanged(mediaMetadata: MediaMetadata) {}

        fun onIsLoadingChanged(isLoading: Boolean) {}

        fun onAvailableCommandsChanged(availableCommands: Any) {}

        fun onPlayerError(error: PlaybackException) {}

        fun onPlayerErrorChanged(error: PlaybackException?) {}

        fun onPlaybackParametersChanged(playbackParameters: PlaybackParameters) {}

        fun onSeekBackIncrementChanged(seekBackIncrementMs: Long) {}

        fun onSeekForwardIncrementChanged(seekForwardIncrementMs: Long) {}

        fun onMaxSeekToPreviousPositionChanged(maxSeekToPreviousPositionMs: Long) {}

        fun onAudioSessionIdChanged(audioSessionId: Int) {}

        fun onAudioAttributesChanged(audioAttributes: AudioAttributes) {}

        fun onVolumeChanged(volume: Float) {}

        fun onSkipSilenceEnabledChanged(skipSilenceEnabled: Boolean) {}

        fun onDeviceInfoChanged(deviceInfo: Any) {}

        fun onDeviceVolumeChanged(volume: Int, muted: Boolean) {}

        fun onCues(cueGroup: Any) {}

        fun onVideoSizeChanged(videoSize: VideoSize) {}

        fun onSurfaceSizeChanged(width: Int, height: Int) {}

        fun onRenderedFirstFrame() {}

        fun onEvents(player: Player, events: Any) {}

        fun onMetadata(metadata: Any) {}
    }

    data class PositionInfo(val mediaItemIndex: Int = 0, val positionMs: Long = 0L, val mediaItem: MediaItem? = null)

    @Target(
        AnnotationTarget.VALUE_PARAMETER,
        AnnotationTarget.FIELD,
        AnnotationTarget.PROPERTY,
        AnnotationTarget.FUNCTION,
    )
    @Retention(AnnotationRetention.RUNTIME)
    annotation class State

    companion object {
        const val COMMAND_PLAY_PAUSE = 1
        const val COMMAND_PREPARE = 2
        const val COMMAND_STOP = 3
        const val COMMAND_SEEK_TO_DEFAULT_POSITION = 4
        const val COMMAND_SEEK_IN_CURRENT_MEDIA_ITEM = 5
        const val COMMAND_SEEK_TO_PREVIOUS_MEDIA_ITEM = 6
        const val COMMAND_SEEK_TO_PREVIOUS = 7
        const val COMMAND_SEEK_TO_NEXT_MEDIA_ITEM = 8
        const val COMMAND_SEEK_TO_NEXT = 9
        const val COMMAND_SEEK_TO_MEDIA_ITEM = 10
        const val COMMAND_SET_SPEED_AND_PITCH = 13
        const val COMMAND_SET_VOLUME = 15
        const val COMMAND_SET_REPEAT_MODE = 17
        const val COMMAND_SET_SHUFFLE_MODE = 18
        const val COMMAND_GET_CURRENT_MEDIA_ITEM = 20
        const val COMMAND_GET_TIMELINE = 21
        const val COMMAND_GET_METADATA = 22
        const val COMMAND_SET_MEDIA_ITEM = 31
        const val COMMAND_CHANGE_MEDIA_ITEMS = 32
        const val COMMAND_GET_AUDIO_ATTRIBUTES = 33
        const val COMMAND_GET_TRACKS = 35
        const val STATE_IDLE = 1
        const val STATE_BUFFERING = 2
        const val STATE_READY = 3
        const val STATE_ENDED = 4

        const val REPEAT_MODE_OFF = 0
        const val REPEAT_MODE_ONE = 1
        const val REPEAT_MODE_ALL = 2

        const val DISCONTINUITY_REASON_AUTO_TRANSITION = 0
        const val DISCONTINUITY_REASON_SEEK = 1
        const val DISCONTINUITY_REASON_SEEK_ADJUSTMENT = 2
        const val DISCONTINUITY_REASON_SKIP = 3
        const val DISCONTINUITY_REASON_REMOVE = 4
        const val DISCONTINUITY_REASON_INTERNAL = 5

        const val MEDIA_ITEM_TRANSITION_REASON_REPEAT = 0
        const val MEDIA_ITEM_TRANSITION_REASON_AUTO = 1
        const val MEDIA_ITEM_TRANSITION_REASON_SEEK = 2
        const val MEDIA_ITEM_TRANSITION_REASON_PLAYLIST_CHANGED = 3

        const val TIMELINE_CHANGE_REASON_PLAYLIST_CHANGED = 0
        const val TIMELINE_CHANGE_REASON_SOURCE_UPDATE = 1

        const val PLAY_WHEN_READY_CHANGE_REASON_USER_REQUEST = 1
    }
}

