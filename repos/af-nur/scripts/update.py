def selected(record: str, args) -> bool:
    return not args.filter or bool(re.search(args.filter, record))


def extract_path(record: str, rel: str, env: dict) -> Path:
    """Path of an extracted lock file from the generated `extract` attribute."""
    expr = (
        f"let repo = {str(REPO_ROOT)};"
        "    flake = builtins.getFlake (toString repo);"
        "    pkgs = import flake.inputs.nixpkgs { system = builtins.currentSystem; };"
        "    gen = import (repo + \"/_sources/generated.nix\");"
        "    sources = gen (builtins.intersectAttrs (builtins.functionArgs gen) pkgs);"
        f"in builtins.toString sources.{record}.extract.\"{rel}\""
    )
    try:
        proc = run(["nix", "eval", "--impure", "--raw", "--expr", expr], env=env, capture=True)
        for line in reversed((proc.stdout or "").splitlines()):
            candidate = Path(line.strip())
            if candidate.is_file() and str(candidate).startswith("/nix/store/"):
                return candidate
    except UpdateError:
        log(f"warning: evaluating the generated extract path for {record} failed, "
            "falling back to the build directory")
    candidates = sorted(BUILD_DIR.glob(f"sha256-*/{rel}"))
    if len(candidates) != 1:
        raise UpdateError(
            f"expected exactly one extracted {rel} for {record} in {BUILD_DIR}, "
            f"found {len(candidates)}"
        )
    return candidates[0]


def bun2nix_cli(env: dict) -> Path:
    """Build the bun2nix CLI from the vendored submodule (matches the shim)."""
    proc = run(
        ["nix", "build", "--no-link", "--print-out-paths", "./vendor/bun2nix#bun2nix"],
        env=env,
        capture=True,
    )
    paths = [line for line in proc.stdout.splitlines() if line.strip().startswith("/nix/store/")]
    if not paths:
        raise UpdateError("could not build the vendored bun2nix CLI")
    cli = Path(paths[-1]) / "bin" / "bun2nix"
    if not cli.is_file():
        raise UpdateError(f"{cli} is missing from the vendored bun2nix build")
    return cli


def regenerate_bun_manifests(args, env: dict) -> list[str]:
    jobs = [
        (record, rel, out)
        for record, entries in BUN_MANIFESTS.items()
        if selected(record, args)
        for rel, out in entries
    ]
    if not jobs:
        return []
    cli = bun2nix_cli(env)

    changed = []
    for record, rel, out_rel in jobs:
        lock = extract_path(record, rel, env)
        out_path = REPO_ROOT / out_rel
        with tempfile.TemporaryDirectory(prefix="nur-update-bun-") as tmp:
            # The build substitutes the npmmirror registry for the canonical one
            # before installing; generate against the canonical URLs too.
            lock_text = lock.read_text().replace(
                "https://registry.npmmirror.com/", "https://registry.npmjs.org/"
            )
            local_lock = Path(tmp) / "bun.lock"
            local_lock.write_text(lock_text)
            generated = Path(tmp) / "bun.nix"
            run([cli, "-l", local_lock, "-o", generated], env=env)
            parse_check_bun(generated)
            new_text = generated.read_text()

        check_bun_manifest(record, out_rel, new_text, out_path)
        if write_if_changed(out_path, new_text):
            changed.append(out_rel)
    return changed


def check_bun_manifest(record: str, out_rel: str, new_text: str, out_path: Path) -> None:
    if "Autogenerated by `bun2nix`" not in new_text:
        raise UpdateError(f"{out_rel}: bun2nix output looks wrong")
    if re.search(r"copyPathToStore", new_text) and (
        out_path.is_file() and not re.search(r"copyPathToStore", out_path.read_text())
    ):
        raise UpdateError(
            f"{out_rel}: the lock file now contains workspace/file dependencies, which "
            "the bun.nix consumer cannot resolve from the repository; wire them up "
            "manually before committing"
        )
    old_count = len(re.findall(r" = (fetchurl|fetchgit|fetchFromGitHub|copyPathToStore) ", out_path.read_text())) \
        if out_path.is_file() else 0
    new_count = len(re.findall(r" = (fetchurl|fetchgit|fetchFromGitHub|copyPathToStore) ", new_text))
    if old_count and new_count < old_count * 0.9:
        raise UpdateError(
            f"{out_rel}: regenerated manifest shrank from {old_count} to {new_count} "
            "entries; refusing to write it"
        )


def parse_check_bun(path: Path) -> None:
    """Make sure a regenerated manifest is syntactically valid Nix."""
    proc = subprocess.run(
        ["nix-instantiate", "--parse", str(path)],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr, end="")
        raise UpdateError(f"{path.name}: regenerated bun manifest does not parse")


def regenerate_go_vendor_hash(args, env: dict) -> list[str]:
    changed = []
    for record, (rel_path, extra_args) in GO_VENDOR_HASH.items():
        if not selected(record, args):
            continue
        expr = f"""
          let
            repo = {str(REPO_ROOT)};
            flake = builtins.getFlake (toString repo);
            pkgs = import flake.inputs.nixpkgs {{
              system = builtins.currentSystem;
              config = {{ allowUnfree = true; allowInsecurePredicate = _: true; }};
            }};
            gen = import (repo + "/_sources/generated.nix");
            sources = gen (builtins.intersectAttrs (builtins.functionArgs gen) pkgs);
            bun2nix = pkgs.callPackage (repo + "/pkgs/bun2nix-shim") {{ }};
            pkg = pkgs.callPackage (repo + "/{rel_path}") {extra_args};
          in (pkg.overrideAttrs (_: {{ vendorHash = pkgs.lib.fakeHash; }})).goModules
        """
        proc = subprocess.run(
            ["nix", "build", "--no-link", "--impure", "--expr", expr],
            cwd=str(REPO_ROOT), env=env, capture_output=True, text=True,
        )
        match = re.search(r"got:\s+(sha256-[A-Za-z0-9+/=]+)", proc.stdout + proc.stderr)
        if not match:
            if proc.returncode == 0:
                log(f"{record}: Go vendor hash already up to date")
                continue
            print(proc.stdout + proc.stderr, file=sys.stderr, end="")
            raise UpdateError(f"{record}: could not determine the Go vendor hash")
        new_hash = match.group(1)

        path = REPO_ROOT / rel_path
        text = path.read_text()
        updated, count = re.subn(
            r'vendorHash = "(sha256-[A-Za-z0-9+/=]+)";',
            f'vendorHash = "{new_hash}";',
            text,
        )
        if count != 1:
            raise UpdateError(f"{rel_path}: expected exactly one vendorHash, found {count}")
        if write_if_changed(path, updated):
            changed.append(rel_path)
        else:
            log(f"{record}: Go vendor hash unchanged")
    return changed


def regenerate_npm_deps_hashes(args, env: dict) -> list[str]:
    """Refresh the npmDepsHash of every npm-locked source.

    The hash covers the fetchNpmDeps cache (tarballs plus, for workspace
    projects, packuments), so it has to be recomputed whenever the extracted
    package-lock.json moves. The package expression takes npmDepsHash as an
    argument, so the cache can be built with the fake hash and the real one
    read back out of the mismatch - which also keeps the fetcher version in
    sync with the package expression instead of duplicating it here.
    """
    changed = []
    for record, (rel, rel_path) in NPM_DEPS_HASH.items():
        if not selected(record, args):
            continue
        # The hash belongs to the extracted lock; make sure nvfetcher produced
        # it before spending a download on the cache.
        extract_path(record, rel, env)
        expr = f"""
          let
            repo = {str(REPO_ROOT)};
            flake = builtins.getFlake (toString repo);
            pkgs = import flake.inputs.nixpkgs {{
              system = builtins.currentSystem;
              config = {{ allowUnfree = true; allowInsecurePredicate = _: true; }};
            }};
            gen = import (repo + "/_sources/generated.nix");
            sources = gen (builtins.intersectAttrs (builtins.functionArgs gen) pkgs);
          in (pkgs.callPackage (repo + "/{rel_path}") {{
            inherit sources;
            npmDepsHash = pkgs.lib.fakeHash;
          }}).npmDeps
        """
        proc = subprocess.run(
            ["nix", "build", "--no-link", "--impure", "--expr", expr],
            cwd=str(REPO_ROOT), env=env, capture_output=True, text=True,
        )
        match = re.search(r"got:\s+(sha256-[A-Za-z0-9+/=]+)", proc.stdout + proc.stderr)
        if not match:
            if proc.returncode == 0:
                log(f"{record}: npm deps hash already up to date")
                continue
            print(proc.stdout + proc.stderr, file=sys.stderr, end="")
            raise UpdateError(f"{record}: could not determine the npm deps hash")
        new_hash = match.group(1)

        path = REPO_ROOT / rel_path
        text = path.read_text()
        updated, count = re.subn(
            r'npmDepsHash \? "(sha256-[A-Za-z0-9+/=]+)"',
            f'npmDepsHash ? "{new_hash}"',
            text,
        )
        if count != 1:
            raise UpdateError(f"{rel_path}: expected exactly one npmDepsHash default, found {count}")
        if write_if_changed(path, updated):
            changed.append(rel_path)
        else:
            log(f"{record}: npm deps hash unchanged")
    return changed


def regenerate_pubspec_locks(args, env: dict) -> list[str]:
    """Refresh the JSON pubspec locks the Flutter builds consume."""
    jobs = [
        (record, rel, out)
        for record, entries in PUBSPEC_LOCKS.items()
        if selected(record, args)
        for rel, out in entries
    ]
    if not jobs:
        return []
    if shutil.which("yq") is None:
        raise UpdateError("yq is missing; run this through scripts/update.sh")

    changed = []
    for record, rel, out_rel in jobs:
        lock = extract_path(record, rel, env)
        proc = run(["yq", "-o=json", ".", lock], env=env, capture=True)
        data = json.loads(proc.stdout)
        if not isinstance(data.get("packages"), dict) or not data["packages"]:
            raise UpdateError(f"{record}: {rel} produced no packages")
        if "sdks" not in data:
            raise UpdateError(f"{record}: {rel} produced no sdks section")
        git_deps = [name for name, meta in data["packages"].items()
                    if meta.get("source") == "git"]
        if git_deps:
            raise UpdateError(
                f"{record}: {rel} now has git dependencies ({', '.join(sorted(git_deps))}); "
                "they need a gitHashes attribute in the package expression"
            )
        out_path = REPO_ROOT / out_rel
        if out_path.is_file():
            old = json.loads(out_path.read_text())
            old_count = len(old.get("packages", {}))
            if old_count and len(data["packages"]) < old_count * 0.9:
                raise UpdateError(
                    f"{out_rel}: regenerated lock shrank from {old_count} to "
                    f"{len(data['packages'])} packages; refusing to write it"
                )
        if write_if_changed(out_path, proc.stdout if proc.stdout.endswith("\n") else proc.stdout + "\n"):
            changed.append(out_rel)
    return changed


def update_flake_lock(args, env: dict) -> bool:
    if args.skip_flake:
        log("skipping flake.lock (--skip-flake)")
        return False
    if args.filter and not args.force_global:
        log("skipping flake.lock (--filter; use --force-global to update it anyway)")
        return False
    run(["nix", "flake", "update"], env=env)
    return True


def submodule_head() -> str:
    proc = subprocess.run(
        ["git", "-C", "vendor/bun2nix", "rev-parse", "HEAD"],
        cwd=str(REPO_ROOT), capture_output=True, text=True,
    )
    if proc.returncode != 0:
        raise UpdateError(
            "could not read vendor/bun2nix HEAD; initialize the submodule "
            "(git submodule update --init)"
        )
    return proc.stdout.strip()


def submodule_gitlink() -> str:
    """Recorded gitlink in the parent repository, used for rollback."""
    proc = subprocess.run(
        ["git", "rev-parse", "HEAD:vendor/bun2nix"],
        cwd=str(REPO_ROOT), capture_output=True, text=True,
    )
    return proc.stdout.strip() if proc.returncode == 0 else ""


def checkout_submodule(rev: str) -> None:
    """Best-effort rollback of the vendored submodule to a recorded gitlink."""
    if not rev:
        return
    proc = subprocess.run(
        ["git", "checkout", "--quiet", "--force", rev],
        cwd=str(REPO_ROOT / "vendor" / "bun2nix"), capture_output=True, text=True,
    )
    if proc.returncode == 0:
        log(f"vendor/bun2nix restored to {rev[:12]}")
    else:
        log(f"warning: could not restore vendor/bun2nix to {rev[:12]}: "
            f"{(proc.stderr or '').strip()}")


def update_vendor_bun2nix(args, env: dict, txn: "Transaction") -> bool:
    """Bump vendor/bun2nix only when asked, and only if the shim survives.

    The submodule stays frozen by default: pkgs/bun2nix-shim calls into the
    vendored tree and pins the helper version, so a new upstream branch is only
    useful once it has been built and exercised. `--vendor` attempts the bump
    and reverts it unless the shim still evaluates and the freshly built CLI
    regenerates a parsable manifest. A bump that passes validation is still
    undone if a later step fails, so the tree never ends up with a new vendored
    tree but an old shim.
    """
    if args.skip_vendor:
        log("skipping vendor/bun2nix (--skip-vendor)")
        return False
    if not args.vendor:
        try:
            current = submodule_head()
        except UpdateError:
            current = ""
        log(f"vendor/bun2nix frozen at {current[:12] or '(uninitialized)'} "
            "(--vendor attempts a validated bump)")
        return False
    if args.filter and not args.force_global:
        log("skipping vendor/bun2nix (--filter; use --force-global to update it anyway)")
        return False

    before = submodule_head()
    rollback_rev = submodule_gitlink() or before
    txn.on_rollback(lambda: checkout_submodule(rollback_rev))
    run(["git", "submodule", "update", "--init", "--remote", "--", "vendor/bun2nix"], env=env)
    after = submodule_head()
    if before == after:
        log(f"vendor/bun2nix unchanged ({after[:12]})")
        return False

    sync_shim_version()
    validate_vendor(env)
    log(f"vendor/bun2nix: {before[:12] or '(none)'} -> {after[:12]}")
    return True


def vendored_bun2nix_version() -> str:
    text = (REPO_ROOT / "vendor/bun2nix/programs/bun2nix/Cargo.toml").read_text()
    match = re.search(r'^version = "([^"]+)"$', text, re.MULTILINE)
    if match is None:
        raise UpdateError("cannot read the vendored bun2nix version")
    return match.group(1)


def sync_shim_version() -> None:
    """Keep the shim's helper version in step with the vendored bun2nix."""
    version = vendored_bun2nix_version()
    path = REPO_ROOT / "pkgs/bun2nix-shim/default.nix"
    text = path.read_text()
    updated, count = re.subn(
        r'^(\s*)version = "[^"]+";$', rf'\g<1>version = "{version}";', text, flags=re.MULTILINE
    )
    if count != 2:
        raise UpdateError(f"pkgs/bun2nix-shim/default.nix: expected 2 version fields, found {count}")
    write_if_changed(path, updated)


def validate_vendor(env: dict) -> None:
    """Prove the bumped vendor tree still fits the shim and its CLI."""
    for required in VENDOR_REQUIRED_PATHS:
        if not (REPO_ROOT / required).is_file():
            raise UpdateError(f"{required} is missing; pkgs/bun2nix-shim expects it")

    # Evaluate the shim exactly the way the packages do, then build the setup
    # hook: it substitutes paths out of the vendored tree, so building it is the
    # cheapest real proof that the interface survived the bump.
    shim_expr = (
        f"let repo = {str(REPO_ROOT)};"
        "    flake = builtins.getFlake (toString repo);"
        "    pkgs = import flake.inputs.nixpkgs { system = builtins.currentSystem; };"
        f"    shim = pkgs.callPackage (repo + \"/pkgs/bun2nix-shim\") {{ }};"
        "in shim.passthru.hook"
    )
    run(["nix", "build", "--no-link", "--impure", "--expr", shim_expr], env=env)

    cli = bun2nix_cli(env)
    sample = next(iter(sorted((REPO_ROOT / "vendor/bun2nix/templates").rglob("bun.lock"))), None)
    if sample is None:
        raise UpdateError("no vendored bun.lock available to exercise the new bun2nix CLI")
    with tempfile.TemporaryDirectory(prefix="nur-update-vendor-") as tmp:
        out = Path(tmp) / "bun.nix"
        run([cli, "-l", sample, "-o", out], env=env)
        parse_check_bun(out)


def update_mefrpc(args, env: dict) -> bool:
    """Run the out-of-tree mefrpc updater when its API is reachable."""
    if args.skip_mefrpc:
        return False
    if not args.mefrpc:
        log("skipping mefrpc (--mefrpc enables it; the package is meta.broken)")
        return False
    probe = subprocess.run(
        ["curl", "-fsS", "-m", "15", "https://api.mefrp.com/api/auth/products"],
        capture_output=True, text=True, env=env,
    )
    if probe.returncode != 0:
        log("mefrpc: version API unreachable, skipping (package stays broken/pinned)")
        return False
    try:
        run(["bash", "update.sh"], cwd=REPO_ROOT / "pkgs" / "mefrpc", env=env)
    except UpdateError as err:
        log(f"mefrpc: updater failed, leaving sources.nix untouched ({err})")
        return False
    return True


