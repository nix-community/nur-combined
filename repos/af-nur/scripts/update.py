def run_nvfetcher(args, env: dict) -> None:
    records = tracked_records()
    fetched = [r for r in records if not args.filter or re.search(args.filter, r)]
    if args.filter and len(fetched) != len(records):
        log(f"filter {args.filter!r} selects {len(fetched)}/{len(records)} records; "
            "the others keep their committed version")
    baseline = GENERATED_JSON.is_file()

    if not args.cache:
        run(["nvfetcher", "-c", CONFIG.name, "-o", BUILD_DIR.name, "purge"], env=env)

    scratch = Path(tempfile.mkdtemp(prefix="nur-update-changes-"))
    changelog = scratch / "changes"
    cmd = [
        "nvfetcher",
        "-c", CONFIG.name,
        "-o", BUILD_DIR.name,
        "-j", str(args.jobs),
        "-r", str(args.retries),
        "-l", str(changelog),
    ]
    # nvchecker honours a keyfile for GitHub API tokens. Reuse the token the CI
    # environment already provides instead of baking anything into the repo.
    keyfile = None
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("NVCHECKER_GITHUB_TOKEN")
    if token:
        keyfile = scratch / "nvchecker-keyfile.toml"
        keyfile.write_text('[keys]\ngithub = ' + json.dumps(token) + "\n")
        keyfile.chmod(0o600)
        cmd += ["-k", str(keyfile)]
        log("using GITHUB_TOKEN for nvchecker API requests")
    if args.filter:
        cmd += ["-f", args.filter]
    if args.keep_going:
        # Collect every failure, then fail as a whole below; without this
        # nvfetcher stops at the first broken record.
        cmd += ["--keep-going"]
    try:
        run(cmd, env=env)
        changes = changelog.read_text().strip() if changelog.is_file() else ""
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    verify_generated(records, filtered=bool(args.filter), baseline=baseline)
    # nvfetcher indents the blank line in an empty cargo outputHashes set.
    GENERATED_NIX.write_text(re.sub(r"(?m)^[ \t]+$", "", GENERATED_NIX.read_text()))
    log("nvfetcher changes:")
    print(changes if changes else "  (no version changes)")


def verify_generated(records: list[str], *, filtered: bool = False, baseline: bool = True) -> None:
    if not GENERATED_NIX.is_file() or not GENERATED_JSON.is_file():
        raise UpdateError("nvfetcher produced no _sources/generated.{nix,json}")
    if GENERATED_MARKER not in GENERATED_NIX.read_text():
        raise UpdateError("_sources/generated.nix does not look like nvfetcher output")

    data = json.loads(GENERATED_JSON.read_text())

    # Every lock file the generated expression points at must exist on disk:
    # nvfetcher cleans the build directory on each run, so a cached extraction
    # step could otherwise leave the expression pointing at nothing.
    for rel in re.findall(r'\./\. \+ "/([^"]+)"', GENERATED_NIX.read_text()):
        if not (BUILD_DIR / rel).is_file():
            raise UpdateError(
                f"_sources/generated.nix references {rel}, but {BUILD_DIR.name}/{rel} "
                "does not exist; nvfetcher reused a cached extraction after cleaning "
                "its build directory (re-run without --cache)"
            )

    missing = sorted(record for record in records if record not in data)
    if missing:
        hint = ""
        if filtered and not baseline:
            hint = (
                "\nThere is no previous _sources/generated.json: with --filter, the records\n"
                "outside the filter have no baseline version to fall back on. Run once\n"
                "without --filter to bootstrap the tree."
            )
        raise UpdateError(
            "nvfetcher produced no record for: " + ", ".join(missing) + "\n"
            "An unreachable upstream is an update failure, not a licence to drop a\n"
            "source that a package depends on. Fix the endpoint or remove the record\n"
            "from nvfetcher.toml together with its consumer; see the nvfetcher output\n"
            "above for the underlying fetch/check error." + hint
        )


