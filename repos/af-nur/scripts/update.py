def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="update.py",
        description="Update every nvfetcher-tracked source plus the secondary lock "
                    "artifacts (bun.nix, Go vendor hash, flake.lock, vendor/bun2nix).",
    )
    parser.add_argument("--filter", metavar="REGEX",
                        help="only refresh records matching this regex (nvfetcher -f); "
                             "global steps stay behind --force-global")
    parser.add_argument("--list", action="store_true",
                        help="print the tracked records and exit")
    parser.add_argument("-j", "--jobs", type=int, default=0,
                        help="nvfetcher parallelism (0 = number of processors)")
    parser.add_argument("-r", "--retries", type=int, default=3,
                        help="nvfetcher retries per rule (default 3)")
    parser.add_argument("--cache", action="store_true",
                        help="keep nvfetcher's cached version/prefetch results instead of "
                             "purging them first")
    parser.add_argument("--keep-going", action="store_true",
                        help="collect every nvfetcher failure instead of stopping at the "
                             "first one (failures still fail the run: a dropped record is "
                             "always an error)")
    parser.add_argument("--skip-flake", action="store_true", help="do not run nix flake update")
    parser.add_argument("--skip-vendor", action="store_true",
                        help="do not touch the vendor/bun2nix submodule at all")
    parser.add_argument("--vendor", action="store_true",
                        help="attempt a validated bump of the vendor/bun2nix submodule "
                             "(frozen by default; the bump is reverted if the shim or the "
                             "vendored CLI stops working)")
    parser.add_argument("--skip-bun", action="store_true",
                        help="do not regenerate the bun.nix manifests")
    parser.add_argument("--skip-npm", action="store_true",
                        help="do not regenerate the npm deps hashes (npm-locked sources)")
    parser.add_argument("--skip-go", action="store_true",
                        help="do not regenerate Go vendor hashes")
    parser.add_argument("--skip-pubspec", action="store_true",
                        help="do not regenerate the JSON pubspec locks (Flutter)")
    parser.add_argument("--skip-mefrpc", action="store_true",
                        help="never touch pkgs/mefrpc/sources.nix")
    parser.add_argument("--mefrpc", action="store_true",
                        help="also run pkgs/mefrpc/update.sh when its API answers")
    parser.add_argument("--force-global", action="store_true",
                        help="also run the global steps (flake.lock, vendor/bun2nix) "
                             "when --filter is set")
    args = parser.parse_args(argv)

    if args.filter:
        try:
            re.compile(args.filter)
        except re.error as err:
            parser.error(f"--filter is not a valid regex: {err}")

    records = tracked_records()
    if args.list:
        for record in records:
            print(record)
        return 0

    env = os.environ.copy()

    regenerated: list[str] = []
    with Transaction(mutable_outputs()) as txn:
        try:
            # Global inputs first: the Go/bun/pubspec helpers must run with the
            # nixpkgs that flake.lock is about to pin, not the previous one.
            if update_flake_lock(args, env):
                regenerated.append("flake.lock")

            locked = resolve_locked_nixpkgs()
            if locked:
                env["NIX_PATH"] = f"nixpkgs={locked}"

            # The vendored bun2nix feeds the bun manifest step below.
            if update_vendor_bun2nix(args, env, txn):
                regenerated.append("vendor/bun2nix")

            run_nvfetcher(args, env)

            if args.skip_bun:
                log("skipping bun.nix manifests (--skip-bun)")
            else:
                regenerated += regenerate_bun_manifests(args, env)
            if args.skip_npm:
                log("skipping npm deps hashes (--skip-npm)")
            else:
                regenerated += regenerate_npm_deps_hashes(args, env)
            if args.skip_go:
                log("skipping Go vendor hashes (--skip-go)")
            else:
                regenerated += regenerate_go_vendor_hash(args, env)
            if args.skip_pubspec:
                log("skipping pubspec locks (--skip-pubspec)")
            else:
                regenerated += regenerate_pubspec_locks(args, env)
            if update_mefrpc(args, env):
                regenerated.append("pkgs/mefrpc/sources.nix")
        except UpdateError as err:
            txn.rollback()
            print(f"error: {err}", file=sys.stderr)
            return 1

    if regenerated:
        log("regenerated: " + ", ".join(sorted(set(regenerated))))
    log("done; review the diff, then commit (this script never commits)")
    status = subprocess.run(
        ["git", "status", "--short", "--", "_sources", "pkgs", "flake.lock", "vendor/bun2nix"],
        cwd=str(REPO_ROOT), capture_output=True, text=True,
    )
    if status.stdout.strip():
        print(status.stdout, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
