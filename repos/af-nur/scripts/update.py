#!/usr/bin/env python3
"""Central dependency updater for nur-packages.

Run it through the wrapper (which provides the toolchain):

    scripts/update.sh                       # everything
    scripts/update.sh --filter '^classin-'  # single record smoke test
    scripts/update.sh --list                # show what is tracked

Steps, in order:

1. refresh the global inputs first (flake.lock, then an opt-in vendor/bun2nix
   bump), so everything below runs on the toolchain that is about to be
   committed;
2. resolve the nixpkgs pin from the refreshed flake.lock, reset nvfetcher's
   caches (unless --cache) and run nvfetcher, which refreshes the upstream
   versions/hashes described by nvfetcher.toml and rewrites
   _sources/generated.nix, _sources/generated.json and the extracted lock files
   (_sources/<sha256-...>/...) that consumers reference;
3. regenerate the secondary artifacts nvfetcher does not own: the bun.nix
   manifests (vendored bun2nix), the npm deps hashes (upstreams locked with
   npm), the Go vendor hash and the JSON pubspec locks;
4. report the version changes and what was rewritten.

The script only writes into: _sources/, pkgs/, flake.lock and vendor/bun2nix.
It never commits or pushes; that is the caller's job.

Exit status is non-zero if nvfetcher dropped a tracked record (a dead upstream
must not silently remove a source a package depends on). Every mutable output
(_sources/, flake.lock and each regenerated lock file) is backed up and restored
on failure, so a failed run leaves the tree exactly as it was.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG = REPO_ROOT / "nvfetcher.toml"
BUILD_DIR = REPO_ROOT / "_sources"
GENERATED_NIX = BUILD_DIR / "generated.nix"
GENERATED_JSON = BUILD_DIR / "generated.json"
GENERATED_MARKER = "# This file was generated by nvfetcher"

# nvfetcher record -> [(lock file inside the source, generated manifest in repo)]
BUN_MANIFESTS = {
    "pixivbiu": [
        ("frontend/bun.lock", "pkgs/pixivbiu/bun.nix"),
    ],
    "rikkahub-desktop": [
        ("web-ui/bun.lock", "pkgs/rikkahub-desktop/bun-web-ui.nix"),
        ("pc-server/bun.lock", "pkgs/rikkahub-desktop/bun-pc-server.nix"),
    ],
}

# nvfetcher record -> (lock file inside the source, package expression)
# Upstreams that lock with npm instead of bun: bun2nix cannot read their
# package-lock.json, so the npm deps cache (and the npmDepsHash pointing at it,
# fetcher version included) is maintained with nixpkgs' fetchNpmDeps.
NPM_DEPS_HASH = {
    "pi": ("package-lock.json", "pkgs/rikkahub-desktop/pi-vendor.nix"),
}

# nvfetcher record -> (package expression, extra callPackage arguments)
GO_VENDOR_HASH = {
    "pixivbiu": ("pkgs/pixivbiu/default.nix", "{ inherit bun2nix sources; }"),
}

# nvfetcher record -> [(lock file inside the source, generated JSON in repo)]
# The Flutter build consumes pubspec.lock converted to JSON, mirroring the
# `curl .../pubspec.lock | yq > pubspec.lock.json` recipe used in nixpkgs.
PUBSPEC_LOCKS = {
    "astral": [
        ("pubspec.lock", "pkgs/astral/pubspec.lock.json"),
    ],
}

# Paths the vendor/bun2nix shim depends on; abort the submodule bump if upstream
# reorganised them instead of silently breaking pkgs/bun2nix-shim.
VENDOR_REQUIRED_PATHS = [
    "vendor/bun2nix/nix/mk-derivation/hook.sh",
    "vendor/bun2nix/programs/cache-entry-creator/deps.nix",
]


class UpdateError(RuntimeError):
    pass


def log(message: str) -> None:
    print(f"[update] {message}", flush=True)


def run(
    cmd,
    *,
    cwd: Path = REPO_ROOT,
    env: dict | None = None,
    capture: bool = False,
) -> subprocess.CompletedProcess:
    printable = " ".join(shlex.quote(str(part)) for part in cmd)
    log(f"$ {printable}")
    proc = subprocess.run(
        [str(part) for part in cmd],
        cwd=str(cwd),
        env=env,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
    )
    if proc.returncode != 0:
        if capture:
            print(proc.stderr or "", file=sys.stderr, end="")
            print(proc.stdout or "", file=sys.stderr, end="")
        raise UpdateError(f"command failed with status {proc.returncode}: {printable}")
    return proc


def tracked_records() -> list[str]:
    """Table names of nvfetcher.toml, i.e. every record that must exist."""
    try:
        import tomllib
    except ModuleNotFoundError:  # pragma: no cover - python < 3.11
        tomllib = None
    text = CONFIG.read_text()
    if tomllib is not None:
        return list(tomllib.loads(text))
    return re.findall(r"^\[([^\]]+)\]$", text, re.MULTILINE)


def resolve_locked_nixpkgs() -> str | None:
    """Path of the nixpkgs revision flake.lock pins, if it can be resolved."""
    expr = "(builtins.getFlake (toString ./.)).inputs.nixpkgs.outPath"
    try:
        proc = subprocess.run(
            ["nix", "eval", "--raw", "--impure", "--expr", expr],
            cwd=str(REPO_ROOT),
            capture_output=True,
            text=True,
            timeout=900,
        )
    except FileNotFoundError:
        raise UpdateError("nix is not in PATH; run this through scripts/update.sh")
    if proc.returncode == 0 and proc.stdout.strip():
        return proc.stdout.strip()
    log("warning: could not resolve the nixpkgs pinned by flake.lock, "
        "falling back to the ambient NIX_PATH")
    return None


def mutable_outputs() -> list[Path]:
    """Every path the updater may rewrite, single source of truth."""
    paths = [
        BUILD_DIR,
        REPO_ROOT / "flake.lock",
        REPO_ROOT / "pkgs" / "bun2nix-shim" / "default.nix",
        REPO_ROOT / "pkgs" / "mefrpc" / "sources.nix",
    ]
    paths += [REPO_ROOT / out for entries in BUN_MANIFESTS.values() for _, out in entries]
    paths += [REPO_ROOT / out for entries in PUBSPEC_LOCKS.values() for _, out in entries]
    paths += [REPO_ROOT / rel for _, rel in NPM_DEPS_HASH.values()]
    paths += [REPO_ROOT / rel for rel, _ in GO_VENDOR_HASH.values()]
    return paths


class Transaction:
    """Back up every mutable output and restore it if the run fails.

    Restoring only _sources/generated.{nix,json} is not enough: nvfetcher drops
    stale extracted lock files from its build directory, and the secondary steps
    may already have written new bun/pubspec/Go/flake outputs. Copying each
    target (whole directory or file) keeps a failed run byte-identical to the
    previous commit. Steps that move state outside these paths (the vendored
    submodule) register a rollback action instead.
    """

    def __init__(self, paths: list[Path]) -> None:
        self._paths = paths
        self._actions: list = []
        self._dir = Path(tempfile.mkdtemp(prefix="nur-update-backup-"))
        self._rolled_back = False

    def __enter__(self) -> "Transaction":
        for index, path in enumerate(self._paths):
            saved = self._dir / str(index)
            if path.is_dir():
                shutil.copytree(path, saved)
            elif path.is_file():
                shutil.copy2(path, saved)
        return self

    def on_rollback(self, action) -> None:
        """Register a best-effort undo for state outside the backed-up paths."""
        self._actions.append(action)

    def rollback(self) -> None:
        if self._rolled_back:
            return
        self._rolled_back = True
        for index, path in enumerate(self._paths):
            saved = self._dir / str(index)
            if saved.is_dir():
                shutil.rmtree(path, ignore_errors=True)
                shutil.copytree(saved, path)
            elif saved.is_file():
                shutil.copy2(saved, path)
            elif path.is_dir():
                shutil.rmtree(path, ignore_errors=True)
            elif path.is_file():
                path.unlink()
        for action in reversed(self._actions):
            action()
        log("restored the previous _sources and secondary lock outputs")

    def __exit__(self, exc_type, exc, tb) -> None:
        try:
            # Anything that is not caught in main (OSError, JSONDecodeError,
            # KeyboardInterrupt, ...) must not leave a half-updated tree.
            if exc_type is not None:
                self.rollback()
        finally:
            shutil.rmtree(self._dir, ignore_errors=True)


def write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text() == content:
        return False
    path.write_text(content)
    log(f"wrote {path.relative_to(REPO_ROOT)}")
    return True


