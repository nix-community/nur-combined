use super::{Action, Step};
use crate::Page;

fn topic(
    category: &'static str,
    title: &'static str,
    description: &'static str,
    example: &str,
    tip: &'static str,
    action: Option<(&'static str, Action)>,
) -> Step {
    let (button, action) = match action {
        Some((button, action)) => (button, Some(action)),
        None => ("", None),
    };
    Step {
        category,
        title,
        description,
        example: example.into(),
        tip,
        button,
        action,
    }
}

